РЕЖИМЫ = {"модуль": "--режим=модуль", "фрагмент": "--режим=фрагмент", "манифест": "--режим=манифест"}


def прототип(данные, режим):
    try:
        if isinstance(данные, bytes):
            разобрать_байты(данные, режим)
        else:
            разобрать(данные, режим)
        return None
    except ОшибкаРазбора as ошибка:
        return str(ошибка)


def компилятор(сплав, данные, режим):
    байты = данные if isinstance(данные, bytes) else данные.encode("utf-8")
    итог = subprocess.run([str(сплав), "дерево", РЕЖИМЫ[режим], "-"], input=байты, capture_output=True)
    строки = итог.stderr.decode("utf-8", "replace").splitlines()
    if итог.returncode == 0 and not строки:
        return None
    if итог.returncode != 1 or len(строки) != 1 or not строки[0].startswith("-:"):
        return f"код {итог.returncode}: {строки}"
    return строки[0][2:]


def сверить(сплав, название, данные, режим, ожидается_успех, расхождения):
    ожидаемое = прототип(данные, режим)
    полученное = компилятор(сплав, данные, режим)
    замечания = []
    if ожидается_успех is not None and (ожидаемое is None) != ожидается_успех:
        замечания.append(f"прототип: {ожидаемое or 'принят'}")
    if полученное != ожидаемое:
        замечания.append(f"прототип: {ожидаемое or 'принят'}")
        замечания.append(f"сплав:    {полученное or 'принят'}")
    if замечания:
        расхождения.append(название)
        print(f"✗ {название}" + "".join(f"\n    {замечание}" for замечание in dict.fromkeys(замечания)))
    return not замечания


def главная(аргументы):
    сплав = СПЛАВ_ПО_УМОЛЧАНИЮ
    for аргумент in аргументы:
        if аргумент.startswith("--сплав="):
            сплав = pathlib.Path(аргумент.removeprefix("--сплав="))
    if not сплав.exists():
        print(f"нет исполняемого файла {сплав}: соберите компилятор или укажите --сплав=путь")
        return False
    расхождения = []
    основные = [сверить(сплав, *случай, расхождения) for случай in случаи()]
    print(f"случаи грамматика/проверка.py: совпало {sum(основные)} из {len(основные)}")
    прочие = [сверить(сплав, название, исходник, "модуль", None, расхождения) for название, исходник in ВНЕ_ПРОВЕРКИ.items()]
    прочие += [сверить(сплав, название, данные, "модуль", None, расхождения) for название, данные in БАЙТОВЫЕ.items()]
    print(f"случаи вне проверки: совпало {sum(прочие)} из {len(прочие)}")
    print(f"сверка с прототипом: {sum(основные) + sum(прочие)} из {len(основные) + len(прочие)}")
    return not расхождения


if __name__ == "__main__":
    sys.exit(0 if главная(sys.argv[1:]) else 1)
