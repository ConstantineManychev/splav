import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "модель"))

from прототип import ОшибкаРазбора, разобрать
from проверить import проверить_файл

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
КАТАЛОГ = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else КОРЕНЬ / "корпус" / "злые"
КОДЫ = {f"С04{номер:02d}" for номер in range(1, 21)}
СТРОКА_ДИАГНОСТИКИ = re.compile(r"^( {2})?(\d+):(\d+) (ошибка (С\d{4})|примечание) «([^»]+)»: (.+)$")


def разбирается(путь):
    try:
        разобрать(путь.read_text(encoding="utf-8"), "модуль")
        return None
    except ОшибкаРазбора as ошибка:
        return str(ошибка)


def проверить_файл_диагностик(злой, диагностики):
    замечания = []
    строки = злой.read_text(encoding="utf-8").splitlines()
    ошибок = 0
    for запись in диагностики.read_text(encoding="utf-8").splitlines():
        совпадение = СТРОКА_ДИАГНОСТИКИ.match(запись)
        if совпадение is None:
            замечания.append(f"неверная строка диагностики: {запись}")
            continue
        отступ, строка, столбец, вид, код, якорь, _ = совпадение.groups()
        if вид.startswith("ошибка"):
            ошибок += 1
            if отступ:
                замечания.append(f"ошибка с отступом: {запись}")
            if код not in КОДЫ:
                замечания.append(f"неизвестный код {код}")
        текст = строки[int(строка) - 1] if int(строка) <= len(строки) else ""
        if not текст[int(столбец) - 1:].startswith(якорь):
            замечания.append(f"{строка}:{столбец} не указывает на «{якорь}»")
    if ошибок == 0:
        замечания.append("нет ни одной ошибки")
    return замечания


def проверить_пример(злой):
    имя = злой.name.removesuffix(".спл")
    верный = КАТАЛОГ / f"{имя}.верно.спл"
    диагностики = КАТАЛОГ / f"{имя}.диаг"
    замечания = []
    for путь in (злой, верный):
        if not путь.exists():
            замечания.append(f"нет файла {путь.name}")
        elif (ошибка := разбирается(путь)) is not None:
            замечания.append(f"{путь.name} не разбирается: {ошибка}")
    if not диагностики.exists():
        return замечания + [f"нет файла {диагностики.name}"]
    замечания += проверить_файл_диагностик(злой, диагностики)
    if замечания:
        return замечания
    ожидаемое = диагностики.read_text(encoding="utf-8").splitlines()
    полученное, неподдержано = проверить_файл(злой)
    if полученное != ожидаемое:
        замечания.append("проверка модели памяти выдала другое:")
        замечания += [f"  ждали: {строка}" for строка in ожидаемое if строка not in полученное]
        замечания += [f"  выдано: {строка}" for строка in полученное if строка not in ожидаемое]
    двойник, неподдержано_двойника = проверить_файл(верный)
    if двойник:
        замечания.append(f"{верный.name} отвергнут:")
        замечания += [f"  {строка}" for строка in двойник]
    for модуль, строка, что in неподдержано + неподдержано_двойника:
        замечания.append(f"неподдержано {модуль.имя}:{строка}: {что}")
    return замечания


def главная():
    злые = sorted(путь for путь in КАТАЛОГ.glob("*.спл") if not путь.name.endswith(".верно.спл"))
    if not злые:
        print(f"в {КАТАЛОГ} нет злых примеров")
        return False
    if not any(КАТАЛОГ.glob("*.верно.спл")):
        print(f"в {КАТАЛОГ} нет двойников .верно.спл: это сочетания, их сверяет модель/проверка_сочетаний.py")
        return False
    итог = 0
    for злой in злые:
        замечания = проверить_пример(злой)
        отметка = "✓" if not замечания else "✗"
        print(f"{отметка} {злой.name}" + "".join(f"\n    {замечание}" for замечание in замечания))
        итог += not замечания
    print(f"итого: {итог} из {len(злые)}")
    return итог == len(злые)


sys.exit(0 if главная() else 1)
