import os
import pathlib
import re
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "модель"))

from прототип import ОшибкаРазбора, разобрать, разобрать_байты
from проверить import проверить_файл

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
КАТАЛОГИ = ["корпус/злые", "корпус/злые-синтаксис", "корпус/злые-имена", "корпус/злые-типы"]
КОДЫ_СИНТАКСИСА = {f"С01{номер:02d}" for номер in range(1, 20)}
КОДЫ_ИМЁН = {f"С02{номер:02d}" for номер in range(1, 12)}
КОДЫ_ТИПОВ = {f"С03{номер:02d}" for номер in range(1, 17)}
КОДЫ_ПАМЯТИ = {f"С04{номер:02d}" for номер in range(1, 22)}
КОДЫ = КОДЫ_СИНТАКСИСА | КОДЫ_ИМЁН | КОДЫ_ТИПОВ | КОДЫ_ПАМЯТИ
ПРОВЕРЯЕТ_МОДЕЛЬ = КОДЫ_ПАМЯТИ | {"С0301", "С0302"}
ПРОВЕРЯЕТ_КОМПИЛЯТОР = КОДЫ_ИМЁН | КОДЫ_ТИПОВ - {"С0301", "С0302"}
СПЛАВ = pathlib.Path(os.environ.get("SPLAV", КОРЕНЬ / "сборка" / "dev" / "bin" / ("сплав.exe" if sys.platform == "win32" else "сплав")))
СТРОКА_ДИАГНОСТИКИ = re.compile(r"^( {2})?(\d+):(\d+) (ошибка (С\d{4})|примечание)(?: «([^»]+)»)?: (.+)$")


def разбирается(путь):
    try:
        разобрать_байты(путь.read_bytes(), "модуль")
        return None
    except ОшибкаРазбора as ошибка:
        return str(ошибка)


def проверить_файл_диагностик(злой, диагностики):
    замечания = []
    коды = []
    строки = злой.read_bytes().decode("utf-8", "replace").splitlines()
    for запись in диагностики.read_text(encoding="utf-8").splitlines():
        совпадение = СТРОКА_ДИАГНОСТИКИ.match(запись)
        if совпадение is None:
            замечания.append(f"неверная строка диагностики: {запись}")
            continue
        отступ, строка, столбец, вид, код, якорь, _ = совпадение.groups()
        if вид.startswith("ошибка"):
            коды.append(код)
            if отступ:
                замечания.append(f"ошибка с отступом: {запись}")
            if код not in КОДЫ:
                замечания.append(f"неизвестный код {код}")
        текст = строки[int(строка) - 1] if int(строка) <= len(строки) else ""
        if якорь is not None and not текст[int(столбец) - 1:].startswith(якорь):
            замечания.append(f"{строка}:{столбец} не указывает на «{якорь}»")
    if not коды:
        замечания.append("нет ни одной ошибки")
    return замечания, коды


def сверить_с_компилятором(злой, ожидаемое):
    итог = subprocess.run([str(СПЛАВ), "проверить", str(злой)], capture_output=True)
    префикс = f"{злой}:"
    полученное = []
    for строка in итог.stderr.decode("utf-8", "replace").splitlines():
        полученное.append(строка.removeprefix(префикс))
    if полученное == ожидаемое:
        return []
    return ["компилятор выдал другое:"] + [f"  ждали: {с}" for с in ожидаемое] + [f"  выдано: {с}" for с in полученное]


def проверить_двойника(верный):
    замечания = []
    двойник, неподдержано = проверить_файл(верный)
    if двойник:
        замечания.append(f"{верный.name} отвергнут:")
        замечания += [f"  {строка}" for строка in двойник]
    for модуль, строка, что in неподдержано:
        замечания.append(f"неподдержано {модуль.имя}:{строка}: {что}")
    return замечания


def сверить_с_моделью(злой, ожидаемое):
    замечания = []
    полученное, неподдержано = проверить_файл(злой)
    if полученное != ожидаемое:
        замечания.append("проверка модели выдала другое:")
        замечания += [f"  ждали: {строка}" for строка in ожидаемое if строка not in полученное]
        замечания += [f"  выдано: {строка}" for строка in полученное if строка not in ожидаемое]
    for модуль, строка, что in неподдержано:
        замечания.append(f"неподдержано {модуль.имя}:{строка}: {что}")
    return замечания


def проверить_пример(злой):
    имя = злой.name.removesuffix(".спл")
    верный = злой.with_name(f"{имя}.верно.спл")
    диагностики = злой.with_name(f"{имя}.диаг")
    for путь in (верный, диагностики):
        if not путь.exists():
            return [f"нет файла {путь.name}"], False
    замечания, коды = проверить_файл_диагностик(злой, диагностики)
    ошибка_двойника = разбирается(верный)
    if ошибка_двойника is not None:
        замечания.append(f"{верный.name} не разбирается: {ошибка_двойника}")
    if замечания:
        return замечания, False
    ожидаемое = диагностики.read_text(encoding="utf-8").splitlines()
    ждёт = False
    if set(коды) <= КОДЫ_СИНТАКСИСА:
        полученное = разбирается(злой)
        if полученное is None:
            замечания.append("пример разбирается, а должен быть отвергнут")
        elif [полученное] != ожидаемое:
            замечания += ["разбор выдал другое:", f"  ждали: {ожидаемое}", f"  выдано: {полученное}"]
    else:
        ошибка_злого = разбирается(злой)
        if ошибка_злого is not None:
            return [f"{злой.name} не разбирается: {ошибка_злого}"], False
        if set(коды) <= ПРОВЕРЯЕТ_МОДЕЛЬ:
            замечания += сверить_с_моделью(злой, ожидаемое)
        elif set(коды) <= ПРОВЕРЯЕТ_КОМПИЛЯТОР and СПЛАВ.exists():
            замечания += сверить_с_компилятором(злой, ожидаемое)
        else:
            ждёт = True
    return замечания + проверить_двойника(верный), ждёт


def проверить_каталог(каталог):
    злые = sorted(путь for путь in каталог.glob("*.спл") if not путь.name.endswith(".верно.спл"))
    if not злые:
        print(f"в {каталог} нет злых примеров")
        return 0, 1
    if not any(каталог.glob("*.верно.спл")):
        print(f"в {каталог} нет двойников .верно.спл: это сочетания, их сверяет модель/проверка_сочетаний.py")
        return 0, 1
    прошло = 0
    ждут = 0
    for злой in злые:
        замечания, ждёт = проверить_пример(злой)
        отметка = "✓" if not замечания else "✗"
        пояснение = ": ждёт этапа 2, сверены разбор, позиции и двойник" if ждёт and not замечания else ""
        print(f"{отметка} {злой.name}{пояснение}" + "".join(f"\n    {замечание}" for замечание in замечания))
        прошло += not замечания
        ждут += ждёт and not замечания
    хвост = f", из них ждут этапа 2: {ждут}" if ждут else ""
    print(f"итого: {прошло} из {len(злые)}{хвост}")
    return прошло, len(злые)


def главная(аргументы):
    каталоги = [pathlib.Path(аргумент) for аргумент in аргументы] or [КОРЕНЬ / каталог for каталог in КАТАЛОГИ]
    прошло = 0
    всего = 0
    for каталог in каталоги:
        if len(каталоги) > 1:
            print(f"— {каталог.relative_to(КОРЕНЬ) if каталог.is_relative_to(КОРЕНЬ) else каталог}")
        успешных, примеров = проверить_каталог(каталог)
        прошло += успешных
        всего += примеров
    if len(каталоги) > 1:
        print(f"всего: {прошло} из {всего}")
    return прошло == всего


if __name__ == "__main__":
    sys.exit(0 if главная(sys.argv[1:]) else 1)
