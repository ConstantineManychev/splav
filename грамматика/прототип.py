        вид = self.вид()
        if вид == "запуск":
            self.взять()
            узел = Узел("запуск", первый, значение=self.выражение())
        elif вид == "возврат":
            self.взять()
            значение = self.выражение() if self.вид() not in ("КОНЕЦ", "}", "КФ") else None
            узел = Узел("возврат", первый, значение=значение)
        elif вид in ("прервать", "продолжить"):
            self.взять()
            метка = self.принять("ИДЕНТ")
            узел = Узел(вид, первый, метка=метка.текст if метка else None)
        elif вид == "_" and self.вид(1) == "=":
            self.взять()
            self.взять("=")
            узел = Узел("отбросить", первый, значение=self.выражение())
        else:
            выражение = self.выражение()
            if self.вид() in ПРИСВАИВАНИЯ:
                оператор = self.взять()
                значение = self.выражение()
                узел = Узел("присваивание", первый, оп=оператор.вид, токен_оператора=оператор, цель=выражение, значение=значение)
            else:
                узел = Узел("выражение", первый, значение=выражение)
        return self.готово(узел)

