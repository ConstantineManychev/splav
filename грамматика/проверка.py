СВОДНЫЕ = {"корпус/злые-сочетания"}


def проверить(название, исходник, режим, ожидается_успех=True, правило_глубины=False, тихо=False):
    try:
        разобрать(исходник, режим, правило_глубины)
        результат = "ок"
        успех = ожидается_успех
    except ОшибкаРазбора as ошибка:
        результат = f"ошибка {ошибка}"
        успех = not ожидается_успех
    отметка = "✓" if успех else "✗"
    if not (тихо and успех):
        print(f"{отметка} {название}: {результат}")
    return успех


def блоки_спецификации():
    текст = СПЕЦИФИКАЦИЯ.read_text(encoding="utf-8")
    for номер, (_, тело) in enumerate(re.findall(r"```([^\n]*)\n(.*?)```", текст, re.S)):
        первая = тело.split("\n")[0]
        if первая.endswith("/") and "├" in тело:
            continue
        yield номер, первая, тело


def файлы_корпуса():
    for каталог in КОРПУСЫ:
        место = pathlib.Path(каталог)
        if not место.is_dir():
            место = КОРЕНЬ / каталог
        for путь in sorted(место.glob("*.спл")):
            режим = "манифест" if путь.name == "пакет.спл" else "модуль"
            yield каталог, f"{каталог}/{путь.name}", путь.read_text(encoding="utf-8"), режим


def главная():
    итог = []
    print("— корпус")
    сводка = {}
    for каталог, название, исходник, режим in файлы_корпуса():
        успех = проверить(название, исходник, режим, тихо=каталог in СВОДНЫЕ)
        итог.append(успех)
        if каталог in СВОДНЫЕ:
            всего, хороших = сводка.get(каталог, (0, 0))
            сводка[каталог] = (всего + 1, хороших + успех)
    for каталог, (всего, хороших) in сводка.items():
        print(f"{'✓' if всего == хороших else '✗'} {каталог}: разобрано {хороших} из {всего}")
    print("— примеры спецификации")
    if СПЕЦИФИКАЦИЯ is None:
        искомое = sys.argv[1] if len(sys.argv) > 1 else ШАБЛОН_СПЕЦИФИКАЦИИ
        print(f"✗ нет файла «{искомое}» ни в текущей папке, ни в архиве, ни рядом с ним: экспортируйте спецификацию в Markdown")
        итог.append(False)
    else:
        print(f"  {СПЕЦИФИКАЦИЯ}")
        for номер, первая, тело in блоки_спецификации():
            режим = "манифест" if первая.startswith("Пакет{") else "фрагмент"
            итог.append(проверить(f"блок {номер} «{первая[:48]}»", тело, режим))
    print("— дополнительные конструкции")
    for название, исходник in ДОПОЛНИТЕЛЬНЫЕ.items():
        итог.append(проверить(название, исходник, "модуль"))
    итог.append(проверить("манифест со списком", ДОПОЛНИТЕЛЬНЫЙ_МАНИФЕСТ, "манифест"))
    print("— негативные (должны отвергаться)")
    for название, исходник in НЕГАТИВНЫЕ.items():
        итог.append(проверить(название, исходник, "модуль", ожидается_успех=False))
    print("— правило переводов строк из черновика (глубина скобок вместо стека)")
    проверить(
        "блок внутри скобок вызова по черновику",
        ДОПОЛНИТЕЛЬНЫЕ["блок внутри скобок вызова"],
        "модуль",
        правило_глубины=True,
    )
    print(f"итого: {sum(итог)} из {len(итог)}")


главная()
