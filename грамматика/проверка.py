def найти_спецификацию():
    места = [pathlib.Path.cwd(), КОРЕНЬ, КОРЕНЬ.parent]
    if len(sys.argv) > 1:
        for место in места:
            путь = место / sys.argv[1]
            if путь.is_file():
                return путь
        return None
    for место in места:
        найденные = sorted(место.glob(ШАБЛОН_СПЕЦИФИКАЦИИ), key=lambda путь: путь.stat().st_mtime)
        if найденные:
            return найденные[-1]
    return None


