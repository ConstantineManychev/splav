from collections import defaultdict, deque

from прототип import Узел
from типы import ЗАДАЧА, СТАТИЧ, РегЗначение, Ссылка, линейный, показать

ДОСТУПЫ = {"читать", "переместить", "занять", "писать", "перезапись", "занять_рег"}


def позиция(узел):
    return (узел.строка, узел.столбец)


def имя_региона(регион):
    вид = регион.вид
    if вид == "блок":
        return f"регион `{регион.имя}`" if регион.имя != "регион блока" else "регион блока"
    if вид == "значение":
        return f"регион `{регион.имя}`"
    if вид == "сигнатура":
        роль = getattr(регион, "роль", "")
        if роль == "контекст":
            return "регион контекста"
        if роль == "результат":
            return "регион результата"
        if роль == "захват":
            return f"заём захвата `{регион.параметр}`"
        if getattr(регион, "параметр", None):
            return f"регион параметра `{регион.параметр}`"
        return "регион сигнатуры"
    if вид == "заём":
        return f"заём `{регион.имя}`"
    if вид == "капсула":
        return f"арену капсулы `{регион.имя}`"
    if регион is СТАТИЧ:
        return "`статич`"
    if регион is ЗАДАЧА:
        return "время жизни задачи"
    return регион.имя


def узел_причины(ограничение):
    if ограничение.вид == "запись" and ограничение.данные and ограничение.данные.get("место") is not None:
        return ограничение.данные["место"].узел
    return ограничение.узел


def узел_имени(привязка):
    узел = привязка.узел
    if isinstance(узел, Узел) and узел.вид in ("привязка", "параметр") and getattr(узел, "токен_имени", None) is not None:
        return узел.токен_имени
    return узел


def арена(регион):
    return регион.вид in ("блок", "значение", "сигнатура", "капсула") or регион is СТАТИЧ


class Решатель:
    def __init__(self, анализ, отчёт):
        self.а = анализ
        self.отчёт = отчёт
        self.точки = анализ.точки
        self.контракт = []
        self.в_ошибке = set()

    def ошибка(self, узел, код, сообщение, примечания=()):
        self.отчёт.добавить(self.а.модуль, узел, код, сообщение, list(примечания))

    def текст(self, узел):
        if isinstance(узел, Узел):
            return узел.текст(self.а.исх).split("\n")[0]
        return getattr(узел, "текст", "")

    def запустить(self):
        self.живучесть()
        self.значения_регионов()
        self.границы()
        self.проверить_статику()
        self.проверить_концы()
        self.проверить_конфликты()
        self.проверить_ветви()
        self.линейность()
        return self.контракт

    def живучесть(self):
        n = len(self.точки)
        self.использования = [set() for _ in range(n)]
        self.определения = [set() for _ in range(n)]
        for точка in self.точки:
            данные = точка.данные
            if точка.вид in ("определить", "объявить"):
                self.определения[точка.номер].add(данные["привязка"])
            место = данные.get("место")
            if место is not None and место.корень is not None and точка.вид in ДОСТУПЫ:
                self.использования[точка.номер].add(место.корень)
        живые = [set() for _ in range(n)]
        изменилось = True
        while изменилось:
            изменилось = False
            for точка in reversed(self.точки):
                выход = set()
                for следующая in точка.следующие:
                    выход |= живые[следующая.номер]
                новое = self.использования[точка.номер] | (выход - self.определения[точка.номер])
                if новое != живые[точка.номер]:
                    живые[точка.номер] = новое
                    изменилось = True
        self.живые = живые
        self.живость = defaultdict(set)
        for номер, множество in enumerate(живые):
            for привязка in множество:
                self.живость[привязка].add(номер)

    def значения_регионов(self):
        значения = defaultdict(set)
        for привязка in self.а.привязки:
            точки = self.живость.get(привязка)
            if not точки:
                continue
            for регион in привязка.тип.регионы():
                значения[регион] |= точки
        for регион, начало, конец, _ in self.а.диапазоны:
            if конец >= начало:
                значения[регион] |= set(range(начало, конец + 1))
        изменилось = True
        while изменилось:
            изменилось = False
            for ограничение in self.а.ограничения:
                малое = значения.get(ограничение.малый)
                if малое:
                    большое = значения[ограничение.большой]
                    if not малое <= большое:
                        большое |= малое
                        изменилось = True
        self.значения = значения

    def границы(self):
        нижние = defaultdict(dict)
        верхние = defaultdict(dict)
        ограничения = [о for о in self.а.ограничения if о.вид != "опора"]
        for ограничение in ограничения:
            if ограничение.малый.конкретный():
                нижние[ограничение.большой].setdefault(ограничение.малый, ограничение)
            if ограничение.большой.конкретный():
                верхние[ограничение.малый].setdefault(ограничение.большой, ограничение)
        изменилось = True
        while изменилось:
            изменилось = False
            for ограничение in ограничения:
                for регион in list(нижние.get(ограничение.малый, {})):
                    if регион not in нижние[ограничение.большой]:
                        нижние[ограничение.большой][регион] = ограничение
                        изменилось = True
                for регион in list(верхние.get(ограничение.большой, {})):
                    if регион not in верхние[ограничение.малый]:
                        верхние[ограничение.малый][регион] = ограничение
                        изменилось = True
        self.нижние = нижние
        self.верхние = верхние

    def цепочка(self, от, до):
        итог = []
        текущий = от
        виденные = set()
        while текущий is not до and текущий not in виденные:
            виденные.add(текущий)
            ограничение = self.нижние.get(текущий, {}).get(до)
            if ограничение is None:
                break
            итог.append(ограничение)
            текущий = ограничение.малый
        return итог

    def известно(self, большой, малый):
        if большой is малый:
            return True
        достижимые = {большой}
        очередь = [большой]
        while очередь:
            регион = очередь.pop()
            for б, м in self.а.известные:
                if б is регион and м not in достижимые:
                    достижимые.add(м)
                    очередь.append(м)
        return малый in достижимые

    def статично(self, большой, малый):
        if большой is малый or большой is СТАТИЧ:
            return True
        if малый.вид == "капсула":
            return getattr(малый, "источник", None) is большой
        if малый is СТАТИЧ:
            return False
        if малый is ЗАДАЧА:
            return False
        if большой is ЗАДАЧА:
            return False
        if большой.вид == "капсула":
            return getattr(большой, "опора", None) is not None or малый.вид in ("блок", "значение", "заём")
        if большой.вид == "заём" and малый.вид == "заём":
            return True
        if большой.вид == "сигнатура":
            if малый.вид in ("блок", "значение", "заём"):
                return True
            return None
        if большой.вид == "блок":
            if малый.вид == "блок":
                return большой in малый.внешние
            if малый.вид == "заём":
                корень = малый.место.корень
                return корень is not None and большой in getattr(корень, "блоки", [])
            return False
        return False

    def свои(self, регион):
        return регион.вид == "сигнатура" and (
            регион in self.а.ф.регионы_сигнатуры or регион is self.а.ф.контекст
        )

    def проверить_статику(self):
        сообщено = set()
        for большой, нижние in list(self.нижние.items()):
            if not большой.конкретный():
                continue
            for малый in list(нижние):
                опорный = большой
                if большой.вид == "капсула" and getattr(большой, "опора", None) is not None and малый.вид != "капсула":
                    опорный = большой.опора
                    if not опорный.конкретный():
                        continue
                итог = self.статично(опорный, малый)
                if итог:
                    continue
                if итог is None:
                    if self.свои(опорный) and (self.свои(малый) or малый is ЗАДАЧА or малый is СТАТИЧ):
                        if not self.известно(опорный, малый):
                            причина = self.цепочка(большой, малый)
                            сохраняющие = [о for о in причина if о.вид in ("запись", "возврат", "поле", "хранимость", "выделение")]
                            кандидаты = сохраняющие or причина
                            главная = max(кандидаты, key=lambda о: позиция(узел_причины(о)) if isinstance(узел_причины(о), Узел) else (0, 0)) if кандидаты else None
                            self.контракт.append((опорный, малый, узел_причины(главная) if главная else None))
                        continue
                    if not self.свои(опорный) or not self.свои(малый):
                        continue
                цепочка = self.цепочка(большой, малый)
                if not цепочка:
                    continue
                главное = max(цепочка, key=lambda о: (позиция(о.узел), -о.номер) if isinstance(о.узел, Узел) else (0, 0))
                ключ = (позиция(главное.узел), большой.номер if большой.вид != "заём" else большой.номер)
                if ключ in сообщено:
                    continue
                сообщено.add(ключ)
                self.сообщить_статику(опорный, малый, цепочка, главное)

    def сообщить_статику(self, большой, малый, цепочка, главное):
        узел = главное.узел
        self.в_ошибке.add(большой)
        self.в_ошибке.add(малый)
        функция_главного = главное.данные.get("функция") if главное.данные else None
        контракт = next((о for о in цепочка if о.вид == "контракт" and (функция_главного is None or о.данные["функция"] is функция_главного)), None)
        примечания = []
        if малый is ЗАДАЧА:
            if большой.вид == "заём":
                что = f"ссылкой на локальное место `{большой.имя}`"
            else:
                что = f"ссылкой в {имя_региона(большой)}"
            self.ошибка(узел, "С0415", f"`{self.текст(узел)}` уходит в задачу со {что}: аргументы `запуск` не держат ни заёмов, ни ссылок в арены",
                        примечания)
            return
        if большой.вид == "заём":
            корень = большой.место.корень
            if малый.вид == "сигнатура" and getattr(малый, "роль", "") == "результат":
                возврат = next((о for о in цепочка if о.вид == "возврат"), None)
                if возврат is not None and возврат.данные and возврат.данные.get("узел_возврата") is not None:
                    примечания.append((возврат.данные["узел_возврата"].первый, "возвращается здесь"))
                пояснение = ""
                if корень is not None and getattr(корень, "из_копии", False):
                    пояснение = ": поля варианта, прочитанные через ссылку, связываются копией (§4.4)"
                self.ошибка(большой.узел if isinstance(большой.узел, Узел) else узел, "С0405",
                            f"ссылка на локальное место `{большой.имя}` покидает функцию{пояснение}", примечания)
                return
            куда = имя_региона(малый)
            причина = ""
            if контракт is not None:
                функция = контракт.данные["функция"]
                причина_узел = контракт.данные.get("причина")
                причина = f": `{функция.полное_имя()}` сохраняет её там"
                if isinstance(причина_узел, Узел):
                    примечания.append((причина_узел, f"`{функция.полное_имя()}` сохраняет ссылку здесь", функция.модуль))
            self.ошибка(узел, "С0402", f"ссылка на локальное место `{большой.имя}` уходит в {куда}{причина}", примечания)
            return
        if малый.вид == "капсула":
            self.ошибка(узел, "С0401", f"ссылка в {имя_региона(большой)} попадает в {имя_региона(малый)}: капсула замкнута — "
                        f"её поля указывают только в её арену или в `статич`", примечания)
            return
        if большой.вид == "капсула":
            self.ошибка(узел, "С0401", f"ссылка в {имя_региона(большой)} уходит в {имя_региона(малый)}: снаружи арена капсулы "
                        f"жива только пока капсулу заимствуют", примечания)
            return
        if большой.вид == "блок" and малый.вид == "сигнатура":
            self.ошибка(узел, "С0403", f"ссылка в {имя_региона(большой)} покидает блок через {имя_региона(малый)}", примечания)
            return
        привязки = [о for о in цепочка if о.вид == "привязка" and о.данные]
        if привязки:
            первая = привязки[0].данные["привязка"]
            примечания.append((узел_имени(первая), f"`{первая.имя}` указывает в {имя_региона(большой)}"))
            последняя = привязки[-1].данные["привязка"]
            if последняя is not первая:
                примечания.append((узел_имени(последняя), f"`{последняя.имя}` указывает в {имя_региона(малый)}"))
        причина = ""
        if контракт is not None:
            функция = контракт.данные["функция"]
            причина_узел = контракт.данные.get("причина")
            пара = контракт.данные.get("пара") or (None, None)
            имена = [getattr(р, "параметр", None) for р in пара]
            if all(имена) and имена[0] != имена[1]:
                причина = f": `{функция.полное_имя()}` связывает регионы `{имена[1]}` и `{имена[0]}`"
            else:
                причина = f": `{функция.полное_имя()}` связывает регионы своих параметров"
            if isinstance(причина_узел, Узел):
                примечания.append((причина_узел, f"здесь `{функция.полное_имя()}` связывает регионы параметров", функция.модуль))
        self.ошибка(узел, "С0401", f"{имя_региона(большой)} живёт меньше, чем {имя_региона(малый)}{причина}", примечания)

    def виновник(self, регион, точка):
        достижимые = {регион: None}
        очередь = deque([регион])
        while очередь:
            текущий = очередь.popleft()
            for ограничение in self.а.ограничения:
                if ограничение.большой is текущий and ограничение.малый not in достижимые:
                    достижимые[ограничение.малый] = ограничение
                    очередь.append(ограничение.малый)
        лучший = None
        for привязка in self.а.привязки:
            if точка not in self.живость.get(привязка, ()):
                continue
            for р in привязка.тип.регионы():
                if р in достижимые:
                    путь = []
                    шаг = р
                    while достижимые.get(шаг) is not None:
                        путь.append(достижимые[шаг])
                        шаг = достижимые[шаг].большой
                    if лучший is None or (привязка.временная < лучший[0].временная):
                        лучший = (привязка, путь)
                    break
        return лучший

    def следующее_использование(self, привязка, от):
        виденные = set()
        очередь = deque(точка for точка in self.точки[от].следующие)
        while очередь:
            точка = очередь.popleft()
            if точка.номер in виденные:
                continue
            виденные.add(точка.номер)
            if привязка in self.использования[точка.номер]:
                return точка
            if привязка in self.определения[точка.номер]:
                continue
            очередь.extend(точка.следующие)
        return None

    def проверить_концы(self):
        for блок in self.а.блоки:
            self.проверить_конец(блок, блок.концы, "С0403")
        for регион in self.а.регионы_значений:
            self.проверить_конец(регион, регион.концы, "С0404")
        for регион in self.а.капсулы:
            if регион.концы:
                self.проверить_конец(регион, регион.концы, "С0404")
        концы_областей = defaultdict(list)
        for точка in self.точки:
            if точка.вид == "конец_области":
                for привязка in точка.данные["привязки"]:
                    концы_областей[привязка].append(точка.номер)
        for заём in self.а.заёмы:
            корень = заём.место.корень
            if корень is None or корень.временная:
                continue
            self.проверить_конец(заём, концы_областей.get(корень, []), "С0405")

    def проверить_конец(self, регион, концы, код):
        if регион in self.в_ошибке:
            return
        значения = self.значения.get(регион, set())
        for конец in концы:
            if конец not in значения:
                continue
            виновник = self.виновник(регион, конец)
            if виновник is None:
                continue
            привязка, путь = виновник
            использование = self.следующее_использование(привязка, конец)
            if использование is None or использование.узел is None:
                continue
            примечания = []
            запись = next((о for о in путь if о.вид == "запись" and isinstance(узел_причины(о), Узел)), None)
            if код == "С0403":
                if запись is not None:
                    примечания.append((узел_причины(запись), f"сюда записана ссылка в {имя_региона(регион)}"))
                примечания.append((узел_имени(привязка), "привязка объявлена вне блока `регион`"))
                сообщение = f"`{привязка.имя}` используется после конца блока `регион`, а указывает в его регион"
            elif код == "С0404" and регион.вид == "капсула":
                точка_конца = self.точки[конец]
                перемещена = точка_конца.вид == "переместить"
                примечания.append((точка_конца.узел, "капсулу перемещают здесь" if перемещена else "капсулу перезаписывают здесь"))
                сообщение = (f"`{привязка.имя}` указывает в {имя_региона(регион)}, а капсулу уже "
                             f"{'переместили' if перемещена else 'перезаписали'}: её арена ушла вместе с ней")
            elif код == "С0404":
                точка_конца = self.точки[конец]
                if запись is not None:
                    примечания.append((узел_причины(запись), "сюда записана ссылка в регион"))
                действие = self.текст(точка_конца.узел)
                упакован = isinstance(точка_конца.узел, Узел) and точка_конца.узел.вид == "литерал"
                примечания.append((точка_конца.узел, "регион ушёл в капсулу здесь" if упакован else "регион сброшен здесь"))
                глагол = "сбросил" if действие.endswith(".сбросить()") else "освободил" if действие.endswith(".освободить()") else "забрал"
                if упакован:
                    сообщение = f"`{привязка.имя}` указывает в регион, который ушёл в капсулу `{действие}`: прежние ссылки в него недоступны"
                else:
                    сообщение = f"`{привязка.имя}` указывает в регион, который `{действие}` уже {глагол}"
            else:
                примечания.append((регион.узел, f"заимствование `{регион.имя}`"))
                сообщение = f"`{привязка.имя}` держит заём `{регион.имя}` после конца области `{регион.место.корень.имя}`"
            self.ошибка(использование.узел, код, сообщение, примечания)
            return

    def проверить_конфликты(self):
        for точка in self.точки:
            if точка.вид not in ДОСТУПЫ:
                continue
            место = точка.данные.get("место")
            if место is None or место.корень is None:
                continue
            for заём in self.а.заёмы:
                if заём.точка == точка.номер or заём.место.корень is not место.корень:
                    continue
                if not self.а.пересекаются(заём.место, место):
                    continue
                if точка.данные.get("сквозное") and len(заём.место.путь) > len(место.путь):
                    continue
                if точка.номер not in self.значения.get(заём, ()):
                    continue
                if точка.вид == "занять":
                    изм = точка.данные["заём"].изм
                    if точка.данные["заём"].точка is not None and точка.данные["заём"].точка < заём.точка:
                        continue
                else:
                    изм = точка.вид in ("переместить", "писать", "перезапись", "занять_рег")
                if not (заём.изм or изм):
                    continue
                self.сообщить_конфликт(точка, заём)
                break

    def сообщить_конфликт(self, точка, заём):
        держатель = self.виновник(заём, точка.номер)
        примечания = [(заём.узел, "заимствован здесь")]
        имя_держателя = None
        if держатель is not None:
            привязка, _ = держатель
            использование = self.следующее_использование(привязка, точка.номер)
            if использование is not None and использование.узел is not None:
                примечания.append((использование.узел, "ссылка используется здесь"))
            имя_держателя = привязка.имя if not привязка.временная else None
        место = точка.данные["место"]
        if точка.вид == "переместить" and линейный(место.тип):
            кто = f"ссылка `{имя_держателя}`" if имя_держателя else "ссылка на него"
            self.ошибка(точка.узел, "С0409", f"`{место.описание()}` потребляется, пока жива {кто}", примечания)
            return
        вид = "исключительный " if заём.изм else ""
        self.ошибка(точка.узел, "С0407", f"`{место.описание()}` занято: пока жив {вид}заём `{заём.имя}`, к нему обращаются только через держателя", примечания)

    def проверить_ветви(self):
        сообщено = set()
        for регион, аргумент, вызов, вид in self.а.требования_ветвей:
            источники = [р for р in list(self.верхние.get(регион, {})) + ([регион] if регион.конкретный() else []) if арена(р)]
            if not источники or id(аргумент) in сообщено:
                continue
            сообщено.add(id(аргумент))
            текст = self.текст(аргумент)
            if вид == "вложенный":
                self.ошибка(аргумент, "С0416", f"через `{текст}` ветвь получает `&изм` в общую арену: две задачи писали бы в неё без синхронизации")
                continue
            примечания = []
            for другой, аргумент_другой, вызов_другой, вид_другой in self.а.требования_ветвей:
                if аргумент_другой is аргумент or вызов_другой is вызов or вид_другой != "верх":
                    continue
                if set(self.верхние.get(другой, {})) & set(источники):
                    примечания.append((аргумент_другой, "вторая ветвь получает ту же изменяемую ссылку"))
                    сообщено.add(id(аргумент_другой))
                    break
            self.ошибка(аргумент, "С0408",
                        f"`{текст}` — `&изм` в регион: задаче передают `&изм` только на собственные места функции, а в регионе исключительность не проверяется",
                        примечания)

    def линейность(self):
        отслеживаемые = [п for п in self.а.привязки if п.линейная or isinstance(п.тип, РегЗначение)]
        if not отслеживаемые:
            return
        n = len(self.точки)
        входы = [None] * n
        выходы = [None] * n
        перемещения = defaultdict(set)
        сообщено = set()
        начало = self.точки[0]
        входы[0] = {}
        очередь = deque([0])
        в_очереди = {0}
        while очередь:
            номер = очередь.popleft()
            в_очереди.discard(номер)
            точка = self.точки[номер]
            состояние = {к: set(в) for к, в in (входы[номер] or {}).items()}
            новое = self.переход(точка, состояние, перемещения, сообщено, проверять=False)
            if выходы[номер] != новое:
                выходы[номер] = новое
                for следующая in точка.следующие:
                    объединение = {}
                    for предыдущая in следующая.предыдущие:
                        if выходы[предыдущая.номер] is None:
                            continue
                        for к, в in выходы[предыдущая.номер].items():
                            объединение.setdefault(к, set()).update(в)
                    if объединение != входы[следующая.номер]:
                        входы[следующая.номер] = объединение
                        if следующая.номер not in в_очереди:
                            очередь.append(следующая.номер)
                            в_очереди.add(следующая.номер)
        for точка in self.точки:
            if входы[точка.номер] is None:
                continue
            состояние = {к: set(в) for к, в in входы[точка.номер].items()}
            self.проверить_слияние(точка, выходы, сообщено, перемещения)
            self.переход(точка, состояние, перемещения, сообщено, проверять=True)

    def проверить_слияние(self, точка, выходы, сообщено, перемещения):
        if len(точка.предыдущие) < 2:
            return
        состояния = [выходы[п.номер] for п in точка.предыдущие if выходы[п.номер] is not None]
        if len(состояния) < 2:
            return
        привязки = set()
        for с in состояния:
            привязки |= set(с)
        for привязка in привязки:
            наборы = [frozenset(с.get(привязка, {"нет"})) for с in состояния]
            живые = [("жива" in н or "отложена" in н) for н in наборы]
            мёртвые = [("перемещена" in н or "отложена_пуста" in н) for н in наборы]
            if any(живые) and any(мёртвые) and not all(живые):
                ключ = ("слияние", привязка, точка.номер)
                if привязка in сообщено:
                    continue
                сообщено.add(привязка)
                if точка.вид == "заголовок":
                    перемещение = max(перемещения.get(привязка, {0}))
                    узел = self.точки[перемещение].узел if перемещение else точка.узел
                    self.ошибка(узел, "С0412", f"линейное значение `{привязка.имя}` получено до цикла и потребляется в его теле: второй проход потребил бы его снова",
                                [(узел_имени(привязка), "получено здесь")])
                elif all(н <= {"отложена", "отложена_пуста"} for н in наборы):
                    явные = [п for п in sorted(перемещения.get(привязка, ())) if not self.точки[п].данные.get("из_отложенного")]
                    примечания = [(узел_имени(привязка), "получено здесь")]
                    if явные:
                        примечания.append((self.точки[явные[0]].узел, "перемещено здесь"))
                    self.ошибка(точка.узел, "С0411",
                                f"отложенное потребление `{привязка.имя}` неоднозначно: на одних путях значение перемещено, на других живо",
                                примечания)
                else:
                    self.ошибка(точка.узел, "С0411", f"линейное значение `{привязка.имя}` потреблено не на всех путях",
                                [(узел_имени(привязка), "получено здесь")])

    def переход(self, точка, состояние, перемещения, сообщено, проверять):
        вид = точка.вид
        данные = точка.данные
        if вид == "определить":
            привязка = данные["привязка"]
            if привязка.линейная or isinstance(привязка.тип, РегЗначение):
                прежнее = состояние.get(привязка, {"нет"})
                if прежнее & {"отложена", "отложена_пуста"}:
                    состояние[привязка] = {"отложена"}
                else:
                    состояние[привязка] = {"жива"}
        elif вид == "объявить":
            привязка = данные["привязка"]
            if привязка.линейная:
                состояние[привязка] = {"нет"}
        elif вид == "перезапись":
            корень = данные["место"].корень
            if проверять and "жива" in состояние.get(корень, set()) and корень not in сообщено:
                сообщено.add(корень)
                self.ошибка(точка.узел, "С0411", f"запись в `{корень.имя}` потеряла бы живое линейное значение: прежнее забирают `память.заменить`")
        elif вид in ДОСТУПЫ:
            место = данные.get("место")
            корень = место.корень if место is not None else None
            if корень is not None and корень in состояние:
                прежнее = состояние[корень]
                if данные.get("из_отложенного") and "отложена_пуста" in прежнее and not место.путь:
                    if проверять and прежнее != {"отложена_пуста"} and корень not in сообщено:
                        сообщено.add(корень)
                        откуда = sorted(перемещения.get(корень, ()))
                        примечания = [(self.точки[откуда[0]].узел, "перемещено здесь")] if откуда else []
                        self.ошибка(точка.узел, "С0411",
                                    f"отложенное потребление `{корень.имя}` неоднозначно: на одних путях к выходу значение уже перемещено, на других живо",
                                    примечания)
                    return состояние
                if проверять and прежнее & {"перемещена", "отложена_пуста"} and корень not in сообщено and корень.линейная | isinstance(корень.тип, РегЗначение):
                    сообщено.add(корень)
                    откуда = [п for п in sorted(перемещения.get(корень, ())) if п != точка.номер]
                    примечания = []
                    if откуда:
                        перемещение = self.точки[откуда[0]]
                        пояснение = "перемещено здесь"
                        if перемещение.данные.get("запуск"):
                            пояснение += ": `запуск` перемещает аргументы в задачу"
                        примечания.append((перемещение.узел, пояснение))
                    где = " в задачу" if откуда and self.точки[откуда[0]].данные.get("запуск") else ""
                    self.ошибка(точка.узел, "С0410", f"значение `{корень.имя}` уже перемещено{где}", примечания)
                if вид == "переместить" and not место.путь:
                    перемещения[корень].add(точка.номер)
                    if прежнее <= {"отложена", "отложена_пуста"} and "отложена" in прежнее:
                        состояние[корень] = {"отложена_пуста"}
                    else:
                        состояние[корень] = {"перемещена"}
                elif вид == "переместить":
                    перемещения[корень].add(точка.номер)
                    состояние[корень] = {"перемещена"}
        elif вид == "отложить":
            for привязка in данные["привязки"]:
                if "жива" in состояние.get(привязка, set()):
                    состояние[привязка] = {"отложена"}
        elif вид == "конец_области":
            for привязка in данные["привязки"]:
                if привязка not in состояние:
                    continue
                if проверять and "жива" in состояние[привязка] and привязка not in сообщено:
                    сообщено.add(привязка)
                    self.сообщить_непотреблённое(точка, привязка)
                del состояние[привязка]
        return состояние

    def сообщить_непотреблённое(self, точка, привязка):
        выход = точка.данные.get("выход")
        узел = точка.узел
        if выход == "попытка":
            сообщение = f"линейное значение `{привязка.имя}` не потреблено, если `попытка` выходит из функции досрочно"
        elif выход == "возврат":
            сообщение = f"линейное значение `{привязка.имя}` не потреблено до `возврат`"
        elif выход in ("прервать", "продолжить"):
            сообщение = f"линейное значение `{привязка.имя}` не потреблено до `{выход}`"
        else:
            сообщение = f"линейное значение `{привязка.имя}` не потреблено до конца блока"
        метод = self.потребитель(привязка.тип)
        пояснение = "получено здесь"
        if метод:
            пояснение += f"; `отложить {привязка.имя}.{метод}()` сразу после получения потребит его на всех выходах"
        self.ошибка(узел, "С0411", сообщение, [(узел_имени(привязка), пояснение)])

    def потребитель(self, тип):
        методы = self.а.п.методы_типа(тип)
        for имя, функция in методы.items():
            self.а.п.заголовок(функция)
            if функция.параметры and функция.параметры[0].форма == "сам" and len(функция.параметры) == 1:
                результат = функция.результат
                if getattr(результат, "имя", None) == "пусто":
                    return имя
        return None
