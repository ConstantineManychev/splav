class Анализ:
    def __init__(self, программа, функция, отчёт, родитель=None):
        self.п = программа
        self.ф = функция
        self.модуль = функция.модуль
        self.исх = self.модуль.исходник
        self.отчёт = отчёт
        self.родитель = родитель
        self.в_отложенном = False
        self.точки = []
        self.текущая = None
        self.области = []
        self.ограничения = []
        self.диапазоны = []
        self.заёмы = []
        self.привязки = []
        self.контексты = []
        self.известные = set()
        self.блоки = []
        self.регионы_значений = []
        self.капсулы = []
        self.капсулы_мест = {}
        self.требования_ветвей = []
        self.выходы_функции = []
        self.неподдержано = []
        self.захваты = {}
        self.результаты_замыкания = []
        self.подстановка_типов = {}
        self.конец = None

    def ошибка(self, узел, код, сообщение, примечания=(), якорь=None):
        self.отчёт.добавить(self.модуль, узел, код, сообщение, list(примечания), якорь)

    def заметить(self, узел, что):
        self.неподдержано.append((узел.строка if узел is not None else 0, что))

    def точка(self, вид, узел=None, **данные):
        if self.в_отложенном:
            данные.setdefault("из_отложенного", True)
        точка = Точка(len(self.точки), вид, узел, данные)
        self.точки.append(точка)
        if self.текущая is not None:
            self.связать(self.текущая, точка)
        self.текущая = точка
        return точка

    def связать(self, откуда, куда):
        откуда.следующие.append(куда)
        куда.предыдущие.append(откуда)

    def ограничение(self, большой, малый, узел, вид="подтип", данные=None):
        if большой is малый or большой is None or малый is None:
            return
        self.ограничения.append(Ограничение(большой, малый, узел, вид, данные, len(self.ограничения)))
        опора = getattr(большой, "опора", None)
        if большой.вид == "капсула" and опора is not None and малый.вид != "капсула" and опора is not малый:
            self.ограничения.append(Ограничение(опора, малый, узел, "опора", данные, len(self.ограничения)))

    def новая_капсула(self, имя, узел, источник=None, опора=None):
        регион = Регион("капсула", имя, узел, концы=[], источник=источник, опора=опора)
        self.капсулы.append(регион)
        return регион

    def освежить_капсулы(self, тип, узел, имя, опора=None):
        return заменить_капсулы(тип, lambda составной: self.новая_капсула(имя, узел, опора=опора))

    def капсулы_места(self, база, путь, тип, узел, опора):
        if база.корень is None:
            return self.освежить_капсулы(тип, узел, показать(тип), опора)
        ключ = (база.корень, путь)
        if ключ not in self.капсулы_мест:
            имя = Место(база.корень, путь, тип, False, None, False, узел).описание()
            self.капсулы_мест[ключ] = self.освежить_капсулы(тип, узел, имя, опора)
        return self.капсулы_мест[ключ]

    def закончить_капсулы(self, место, точка, сбросить_кэш=False):
        if место.корень is None or any(шаг[0] in ("разыменование", "срез") for шаг in место.путь):
            return
        регионы = list(капсульные_регионы(место.тип))
        for ключ in list(self.капсулы_мест):
            корень, путь = ключ
            if корень is место.корень and путь[:len(место.путь)] == место.путь:
                регионы += капсульные_регионы(self.капсулы_мест[ключ])
                if сбросить_кэш:
                    del self.капсулы_мест[ключ]
        for регион in регионы:
            if регион.вид == "капсула" and регион.концы is not None and getattr(регион, "опора", None) is None:
                регион.концы.append(точка.номер)

    def подтип(self, а, б, узел, вид="подтип", данные=None):
        if а is б or а is None or б is None:
            return
        if isinstance(а, Простой) and а.имя == "никогда":
            return
        if isinstance(б, Опц) and not isinstance(а, Опц):
            return self.подтип(а, б.внутр, узел, вид, данные)
        if isinstance(а, Ссылка) and isinstance(б, Ссылка):
            self.ограничение(а.регион, б.регион, узел, вид, данные)
            if б.изм:
                self.равны(а.цель, б.цель, узел, вид, данные)
            else:
                self.подтип(а.цель, б.цель, узел, вид, данные)
        elif isinstance(а, Срез) and isinstance(б, Срез):
            self.ограничение(а.регион, б.регион, узел, вид, данные)
            if б.изм:
                self.равны(а.элемент, б.элемент, узел, вид, данные)
            else:
                self.подтип(а.элемент, б.элемент, узел, вид, данные)
        elif isinstance(а, Опц) and isinstance(б, Опц):
            self.подтип(а.внутр, б.внутр, узел, вид, данные)
        elif isinstance(а, Кортеж) and isinstance(б, Кортеж):
            for х, у in zip(а.элементы, б.элементы):
                self.подтип(х, у, узел, вид, данные)
        elif isinstance(а, Массив) and isinstance(б, Массив):
            self.подтип(а.элемент, б.элемент, узел, вид, данные)
        elif isinstance(а, Составной) and isinstance(б, Составной) and а.объявление is б.объявление:
            for номер, (ра, рб) in enumerate(zip(а.регионы_объекта, б.регионы_объекта)):
                if номер == 0 and капсула(а.объявление):
                    continue
                if а.объявление.инвариантен_регион(номер):
                    self.ограничение(ра, рб, узел, вид, данные)
                    self.ограничение(рб, ра, узел, вид, данные)
                else:
                    self.ограничение(ра, рб, узел, вид, данные)
            for номер, (та, тб) in enumerate(zip(а.типы, б.типы)):
                if а.объявление.инвариантен_тип(номер):
                    self.равны(та, тб, узел, вид, данные)
                else:
                    self.подтип(та, тб, узел, вид, данные)
        elif isinstance(а, Арена) and isinstance(б, Арена):
            self.ограничение(а.регион, б.регион, узел, вид, данные)
            self.ограничение(б.регион, а.регион, узел, вид, данные)
        elif isinstance(а, Функция) and isinstance(б, Функция):
            for ра in а.захваченные:
                for рб in б.захваченные:
                    self.ограничение(ра, рб, узел, вид, данные)
            if а.результат is not None and б.результат is not None:
                self.подтип(а.результат, б.результат, узел, вид, данные)

    def равны(self, а, б, узел, вид, данные):
        self.подтип(а, б, узел, вид, данные)
        self.подтип(б, а, узел, вид, данные)

    def освежить(self, тип, узел, имя="привязка"):
        if isinstance(тип, РегЗначение):
            return тип
        замены = {}
        for регион in тип.регионы():
            if регион not in замены:
                замены[регион] = переменная(имя, узел)
        return тип.заменить(замены)

    def держать(self, знач, точка, узел=None):
        if знач is None:
            return
        for регион in знач.тип.регионы():
            if регион.вид in ("переменная", "заём", "блок", "значение"):
                self.диапазоны.append((регион, знач.начало, точка.номер if isinstance(точка, Точка) else точка, узел or знач.узел))

    def номер_текущей(self):
        return self.текущая.номер if self.текущая is not None else len(self.точки)

    def войти(self, вид, узел, регион=None, цикл=None):
        область = Область(вид, узел, регион, цикл)
        self.области.append(область)
        return область

    def учесть(self, привязка):
        self.области[-1].привязки.append(привязка)
        привязка.область = self.области[-1]
        привязка.блоки = [область.регион for область in self.области if область.регион is not None]
        self.привязки.append(привязка)

    def объявить(self, привязка, узел, вид_точки="определить"):
        self.учесть(привязка)
        self.точка(вид_точки, узел, привязка=привязка)

    def найти_привязку(self, имя):
        for область in reversed(self.области):
            for привязка in reversed(область.привязки):
                if привязка.имя == имя:
                    return привязка
        if self.родитель is not None:
            внешняя = self.родитель.найти_привязку(имя)
            if внешняя is not None:
                return self.захватить(внешняя)
        return None

    def захватить(self, внешняя):
        if внешняя in self.захваты:
            return self.захваты[внешняя][0]
        регион = Регион("сигнатура", f"захват {внешняя.имя}", внешняя.узел, роль="захват", параметр=внешняя.имя)
        if self.копия:
            тип = внешняя.тип
            прокси = Привязка(внешняя.имя, тип, False, внешняя.узел, self.области[0], параметр=True)
        else:
            прокси = Привязка(внешняя.имя, Ссылка(False, регион, внешняя.тип), False, внешняя.узел, self.области[0], параметр=True)
            прокси.захват = регион
            прокси.изм_снаружи = внешняя.изм
        прокси.рег = внешняя.рег
        прокси.блоки = []
        self.области[0].привязки.append(прокси)
        self.привязки.append(прокси)
        self.захваты[внешняя] = (прокси, set(), регион)
        return прокси

    def отметить_захват(self, привязка, вид):
        for внешняя, (прокси, виды, _) in self.захваты.items():
            if прокси is привязка:
                виды.add(вид)

    def выйти_до(self, цель, узел, вид):
        for область in reversed(self.области):
            self.закрыть_область(область, узел, вид)
            if область is цель:
                break

    def закрыть_область(self, область, узел, вид):
        for выражение in reversed(область.отложенные):
            self.точка("отложенное", выражение)
            прежнее = self.в_отложенном
            self.в_отложенном = True
            self.вычислить(выражение, режим="инструкция")
            self.в_отложенном = прежнее
        if область.привязки:
            self.точка("конец_области", узел, привязки=list(область.привязки), область=область, выход=вид)
        if область.регион is not None:
            точка = self.точка("конец_региона", узел, регион=область.регион)
            область.регион.концы.append(точка.номер)

    def выйти_из_области(self, узел):
        область = self.области[-1]
        if self.текущая is not None:
            self.закрыть_область(область, узел, "блок")
        self.области.pop()

    def запустить(self):
        self.копия = False
        начало = self.точка("начало", self.ф.узел)
        область = self.войти("функция", self.ф.узел)
        if self.ф.контекст is not None:
            self.контексты.append(self.ф.контекст)
        for параметр in self.ф.параметры:
            if параметр.компил:
                self.подстановка_типов[параметр.имя] = ПараметрТипа(параметр.имя)
                continue
            тип = self.освежить_капсулы(параметр.тип, параметр.узел, параметр.имя)
            привязка = Привязка(параметр.имя, тип, параметр.изм, параметр.узел, область, параметр=True)
            self.объявить(привязка, параметр.узел)
            self.добавить_известные(параметр.тип)
        for имя in self.ф.параметры_владельца:
            self.подстановка_типов[имя] = ПараметрТипа(имя)
        self.ф_результат = self.ф.результат
        for инструкция in self.ф.тело.инструкции:
            self.инструкция(инструкция)
        if self.текущая is not None:
            закрывающая = self.ф.тело.последний
            if self.ф_результат is not None and not self.пустой_результат(self.ф_результат):
                self.заметить(self.ф.тело, "функция без возврата значения")
            self.точка("выход", закрывающая, форма="конец", якорь="}")
            self.выйти_до(область, закрывающая, "конец")
            self.выходы_функции.append(self.текущая)
        self.области.pop()
        self.текущая = None
        конец = self.точка("конец", self.ф.узел)
        for выход in self.выходы_функции:
            if выход is not None:
                self.связать(выход, конец)
        self.конец = конец

    def пустой_результат(self, тип):
        return isinstance(тип, Простой) and тип.имя in ("пусто", "никогда")

    def добавить_известные(self, тип):
        for большой, малый in self.факты_корректности(тип):
            self.известные.add((большой, малый))

    def факты_корректности(self, тип):
        итог = []
        if isinstance(тип, Ссылка):
            for регион in тип.цель.регионы() + капсульные_регионы(тип.цель):
                итог.append((регион, тип.регион))
            итог += self.факты_корректности(тип.цель)
        elif isinstance(тип, Срез):
            for регион in тип.элемент.регионы():
                итог.append((регион, тип.регион))
            итог += self.факты_корректности(тип.элемент)
        elif isinstance(тип, Составной):
            if тип.регионы_объекта:
                объект = тип.регионы_объекта[0]
                for регион in тип.регионы_объекта[1:]:
                    итог.append((регион, объект))
                for аргумент in тип.типы:
                    for регион in аргумент.регионы():
                        итог.append((регион, объект))
            for аргумент in тип.типы:
                итог += self.факты_корректности(аргумент)
        elif isinstance(тип, Опц):
            итог += self.факты_корректности(тип.внутр)
        elif isinstance(тип, Кортеж):
            for элемент in тип.элементы:
                итог += self.факты_корректности(элемент)
        return итог

    def блок(self, узел, вид="блок", регион=None):
        self.войти(вид, узел, регион)
        for инструкция in узел.инструкции:
            if self.текущая is None:
                self.текущая = None
            self.инструкция(инструкция)
        self.выйти_из_области(узел.последний)

    def инструкция(self, узел):
        вид = узел.вид
        if self.текущая is None:
            self.текущая = None
        if вид == "привязка":
            self.инструкция_привязки(узел)
        elif вид == "присваивание":
            self.присваивание(узел)
        elif вид == "выражение":
            знач = self.вычислить(узел.значение, режим="инструкция")
            if знач is not None and линейный(знач.тип) and знач.место is None:
                self.ошибка(узел, "С0411", f"линейное значение типа `{показать(знач.тип)}` не потреблено")
        elif вид == "отбросить":
            знач = self.вычислить(узел.значение)
            if знач is not None and линейный(знач.тип):
                self.ошибка(узел.значение, "С0414", f"линейное значение типа `{показать(знач.тип)}` нельзя отбросить: его потребляют")
            if знач is not None:
                self.держать(знач, self.точка("использовать", узел))
        elif вид == "возврат":
            self.возврат(узел)
        elif вид in ("прервать", "продолжить"):
            self.переход(узел)
        elif вид == "если":
            self.если(узел)
        elif вид == "цикл":
            self.цикл(узел)
        elif вид == "регион":
            self.регион(узел)
        elif вид == "через":
            self.через(узел)
        elif вид == "вместе_блок":
            self.блок(узел.тело, "вместе")
        elif вид == "опасно_блок":
            self.блок(узел.тело, "опасно")
        elif вид == "отложить":
            self.отложить(узел)
        elif вид == "запуск":
            self.запуск(узел)
        else:
            self.заметить(узел, f"инструкция {вид}")

    def инструкция_привязки(self, узел):
        тип = None
        if узел.тип is not None:
            тип = self.разрешить_тип(узел.тип, "привязка")
        if узел.значение is None:
            if тип is None:
                тип = Неизвестный("без значения")
            привязка = Привязка(узел.имя, тип, узел.изм, узел, self.области[-1])
            self.объявить(привязка, узел, "объявить")
            return
        знач = self.вычислить(узел.значение, тип)
        self.связать_значение(узел.имя, узел.изм, знач, узел, тип)

    def связать_значение(self, имя, изм, знач, узел, тип=None):
        if знач is None:
            знач = Знач(Неизвестный("нет значения"), узел, self.номер_текущей())
        if тип is None:
            тип = self.освежить(знач.тип, узел, имя)
        тип = self.освежить_капсулы(тип, узел, имя)
        привязка = Привязка(имя, тип, изм, узел, self.области[-1])
        привязка.отслеживает = знач.отслеживаемое
        привязка.только_чтение = знач.только_чтение
        привязка.из_копии = getattr(знач, "из_копии", False)
        if isinstance(знач.тип, РегЗначение):
            привязка.тип = знач.тип
            привязка.рег = знач.тип.регион
        self.подтип(знач.тип, привязка.тип, узел, "привязка", {"привязка": привязка})
        self.учесть(привязка)
        точка = self.точка("определить", узел, привязка=привязка, знач=знач)
        self.держать(знач, точка)
        return привязка

    def присваивание(self, узел):
        цель = узел.цель
        if узел.оп == "=" and цель.вид == "имя" and self.найти_привязку(цель.имя) is None and not self.глобальное(цель.имя):
            знач = self.вычислить(узел.значение)
            self.связать_значение(цель.имя, False, знач, цель)
            return
        if узел.оп == "=" and цель.вид in ("кортеж", "литерал"):
            знач = self.вычислить(узел.значение)
            self.разобрать_цель(цель, знач, узел)
            return
        if узел.оп == "=" and цель.вид == "заглушка":
            знач = self.вычислить(узел.значение)
            if знач is not None:
                self.держать(знач, self.точка("использовать", узел))
            return
        место = self.место(цель)
        ожидание = место.тип if место is not None else None
        знач = self.вычислить(узел.значение, ожидание)
        if место is None:
            return
        if узел.оп != "=":
            self.точка("читать", цель, место=место)
        self.проверить_запись(место, цель)
        self.нарушить_капсулу(место, цель, "перезаписано")
        if узел.оп == "=" and any(шаг[0] == "разыменование" for шаг in место.путь) and содержит_капсулу(место.тип):
            self.перезапись_капсулы_по_ссылке(место, цель)
        if место.корень is not None and not место.путь and место.корень.линейная and узел.оп == "=":
            точка = self.точка("перезапись", цель, место=место)
        if знач is not None:
            self.подтип(знач.тип, место.тип, узел.значение, "запись", {"место": место})
        if узел.оп == "=" and (капсульные_регионы(место.тип) or any(
                ключ[0] is место.корень for ключ in self.капсулы_мест)):
            self.закончить_капсулы(место, self.точка("перезапись_капсулы", цель, место=место), сбросить_кэш=True)
            if место.корень is not None and not место.путь:
                место.корень.тип = self.освежить_капсулы(место.корень.тип, цель, место.корень.имя)
        if место.корень is not None and not место.путь and узел.оп == "=":
            if isinstance(знач.тип if знач else None, РегЗначение):
                место.корень.рег = знач.тип.регион
            if знач is not None and isinstance(место.корень.тип, Ссылка):
                место.корень.отслеживает = место.корень.отслеживает or знач.отслеживаемое
            точка = self.точка("определить", цель, привязка=место.корень, знач=знач, присваивание=True)
        else:
            точка = self.точка("писать", цель, место=место)
        self.держать(знач, точка)

    def глобальное(self, имя):
        return имя in self.модуль.константы or имя in self.модуль.функции

    def проверить_запись(self, место, узел, действие=None):
        if место.только_чтение:
            self.ошибка(узел, "С0406", f"`{место.описание()}` доступно только для чтения: оно получено через `&` или копией")
            return
        if not место.запись:
            if место.корень is not None and not место.путь and not место.корень.изм:
                return
            if действие is not None:
                self.ошибка(узел, "С0406", f"{действие} `{место.описание()}`, а оно доступно через ссылку для чтения")
                return
            self.ошибка(узел, "С0406", f"запись в `{место.описание()}` через ссылку для чтения")
            return
        if место.через_общую and any(шаг[0] == "разыменование" for шаг in место.путь):
            self.ошибка(узел, "С0406", f"запись в `{место.описание()}` через `&изм`, прочитанную через `&`: "
                        f"всё, что за `&`, только читается")

    def разобрать_цель(self, цель, знач, узел):
        тип = знач.тип if знач else Неизвестный("")
        if цель.вид == "кортеж":
            типы = тип.элементы if isinstance(тип, Кортеж) else [Неизвестный("кортеж")] * len(цель.элементы)
            for элемент, тип_элемента in zip(цель.элементы, типы):
                часть = Знач(тип_элемента, элемент, знач.начало if знач else self.номер_текущей(),
                             отслеживаемое=знач.отслеживаемое if знач else False)
                if элемент.вид == "имя":
                    существующая = self.найти_привязку(элемент.имя)
                    if существующая is not None:
                        место = self.место(элемент)
                        self.подтип(часть.тип, место.тип, элемент, "запись", {"место": место})
                        if isinstance(часть.тип, РегЗначение):
                            существующая.рег = часть.тип.регион
                        self.держать(часть, self.точка("определить", элемент, привязка=существующая, знач=часть, присваивание=True))
                    else:
                        self.связать_значение(элемент.имя, False, часть, элемент)
                elif элемент.вид == "заглушка":
                    pass
                else:
                    self.разобрать_цель(элемент, часть, узел)
            return
        if цель.вид == "литерал":
            if isinstance(тип, Составной):
                собственный = регион_капсулы(тип)
                свежий = None
                if капсула(тип.объявление):
                    свежий = Регион("значение", тип.объявление.поле_рег or "рег", цель, концы=[], источник=цель)
                    self.регионы_значений.append(свежий)
                for метка, значение, _ in цель.элементы:
                    имя_поля = метка or (значение.имя if значение.вид == "имя" else None)
                    if имя_поля is None:
                        continue
                    тип_поля = тип.поле(имя_поля) or Неизвестный("поле")
                    if свежий is not None and имя_поля == тип.объявление.поле_рег:
                        тип_поля = РегЗначение(свежий)
                    elif свежий is not None and собственный is not None:
                        тип_поля = тип_поля.заменить({собственный: свежий})
                    часть = Знач(тип_поля, значение, знач.начало)
                    if значение.вид == "имя":
                        self.связать_значение(значение.имя, False, часть, значение)
                    elif значение.вид == "заглушка":
                        if линейный(тип_поля):
                            self.ошибка(значение, "С0411", f"поле `{имя_поля}` линейного типа отброшено при разборе")
            return

    def возврат(self, узел):
        if узел.значение is not None:
            знач = self.вычислить(узел.значение, self.ф_результат)
            if знач is not None and self.ф_результат is not None:
                self.подтип(знач.тип, self.ф_результат, узел.значение, "возврат", {"узел_возврата": узел})
                if self.ф.замыкание:
                    self.результаты_замыкания.append(знач.тип)
            точка = self.точка("выход", узел, форма="возврат", знач=знач)
            self.держать(знач, точка)
        else:
            self.точка("выход", узел, форма="возврат")
        self.выйти_до(self.области[0], узел, "возврат")
        self.выходы_функции.append(self.текущая)
        self.текущая = None

    def переход(self, узел):
        цель = None
        for область in reversed(self.области):
            if область.цикл is not None and (узел.метка is None or область.цикл["метка"] == узел.метка):
                цель = область
                break
        if цель is None:
            self.заметить(узел, "переход вне цикла")
            self.текущая = None
            return
        self.точка("выход", узел, форма=узел.вид)
        for область in reversed(self.области):
            if область is цель:
                break
            self.закрыть_область(область, узел, узел.вид)
        if узел.вид == "прервать":
            self.закрыть_область(цель, узел, "прервать")
            цель.цикл["выходы"].append(self.текущая)
        else:
            цель.цикл["продолжения"].append(self.текущая)
        self.текущая = None

    def если(self, узел):
        if узел.компил:
            ветвление = self.текущая
            концы = []
            self.текущая = ветвление
            self.блок(узел.то)
            концы.append(self.текущая)
            if узел.иначе is not None:
                self.текущая = ветвление
                if узел.иначе.вид == "если":
                    self.если(узел.иначе)
                else:
                    self.блок(узел.иначе)
                концы.append(self.текущая)
            else:
                концы.append(ветвление)
            self.слить(концы, узел)
            return
        истина, ложь, привязки = self.условие(узел.условие)
        self.текущая = истина
        self.войти("условие", узел)
        for имя, знач, изм in привязки:
            self.связать_значение(имя, изм, знач, знач.узел)
        self.блок(узел.то)
        if self.текущая is not None:
            self.выйти_из_области(узел.то.последний)
        else:
            self.области.pop()
        концы = [self.текущая]
        self.текущая = ложь
        if узел.иначе is not None:
            if узел.иначе.вид == "если":
                self.если(узел.иначе)
            else:
                self.блок(узел.иначе)
        концы.append(self.текущая)
        self.слить(концы, узел)

    def слить(self, концы, узел):
        живые = [конец for конец in концы if конец is not None]
        if not живые:
            self.текущая = None
            return
        self.текущая = None
        слияние = self.точка("слияние", узел)
        for конец in живые:
            self.связать(конец, слияние)
        self.текущая = слияние

    def условие(self, узел):
        if узел.вид == "скобки":
            return self.условие(узел.значение)
        if узел.вид == "логическое" and узел.оп == "и":
            истина_л, ложь_л, привязки_л = self.условие(узел.левый)
            self.текущая = истина_л
            self.войти("условие", узел)
            for имя, знач, изм in привязки_л:
                self.связать_значение(имя, изм, знач, знач.узел)
            истина_п, ложь_п, привязки_п = self.условие(узел.правый)
            self.области.pop()
            ложь = self.точка_слияния([ложь_л, ложь_п], узел)
            return истина_п, ложь, привязки_л + привязки_п
        if узел.вид == "логическое" and узел.оп == "или":
            истина_л, ложь_л, _ = self.условие(узел.левый)
            self.текущая = ложь_л
            истина_п, ложь_п, _ = self.условие(узел.правый)
            истина = self.точка_слияния([истина_л, истина_п], узел)
            return истина, ложь_п, []
        if узел.вид == "не":
            истина, ложь, _ = self.условие(узел.операнд)
            return ложь, истина, []
        if узел.вид == "это" and not узел.отрицание:
            знач = self.вычислить_для_сопоставления(узел.значение)
            ветвление = self.точка("проверка", узел)
            self.держать(знач, ветвление)
            привязки = self.привязки_образца(узел.образец, знач, узел)
            истина = self.точка("ветвь", узел)
            self.текущая = ветвление
            ложь = self.точка("ветвь", узел)
            return истина, ложь, привязки
        знач = self.вычислить(узел)
        ветвление = self.точка("проверка", узел)
        self.держать(знач, ветвление)
        истина = self.точка("ветвь", узел)
        self.текущая = ветвление
        ложь = self.точка("ветвь", узел)
        return истина, ложь, []

    def точка_слияния(self, концы, узел):
        живые = [конец for конец in концы if конец is not None]
        if not живые:
            return None
        if len(живые) == 1:
            return живые[0]
        self.текущая = None
        слияние = self.точка("слияние", узел)
        for конец in живые:
            self.связать(конец, слияние)
        return слияние

    def цикл(self, узел):
        итератор = None
        источник = None
        if узел.источник is not None:
            источник = self.вычислить(узел.источник, режим="перебор", изм=узел.изм)
            итератор = Привязка("итератор", self.освежить(источник.тип, узел, "итератор"), True, узел.источник, self.области[-1], временная=True)
            self.подтип(источник.тип, итератор.тип, узел.источник, "привязка", {"привязка": итератор})
            итератор.отслеживает = источник.отслеживаемое
            self.учесть(итератор)
            self.держать(источник, self.точка("определить", узел.источник, привязка=итератор, знач=источник))
        цикл = {"метка": узел.метка, "выходы": [], "продолжения": [], "узел": узел}
        заголовок = self.точка("заголовок", узел)
        цикл["заголовок"] = заголовок
        область = self.войти("цикл", узел, цикл=цикл)
        выход_по_условию = None
        if узел.условие is not None:
            истина, ложь, привязки = self.условие(узел.условие)
            выход_по_условию = ложь
            self.текущая = истина
            for имя, знач, изм in привязки:
                self.связать_значение(имя, изм, знач, знач.узел)
        elif итератор is not None:
            self.точка("читать", узел.источник, место=Место(итератор, (), итератор.тип, True, None, True, узел.источник))
            элемент = self.элемент_перебора(итератор.тип, узел)
            ветвление = self.текущая
            self.текущая = ветвление
            выход_по_условию = self.точка("ветвь", узел)
            self.текущая = ветвление
            self.точка("ветвь", узел)
            знач = Знач(элемент, узел.образец, self.номер_текущей(), отслеживаемое=итератор.отслеживает)
            self.привязать_образец_перебора(узел.образец, знач)
        self.войти("тело", узел.тело)
        for инструкция in узел.тело.инструкции:
            self.инструкция(инструкция)
        self.выйти_из_области(узел.тело.последний)
        if self.текущая is not None:
            self.закрыть_область(область, узел.тело.последний, "продолжить")
            self.точка("назад", узел)
            self.связать(self.текущая, заголовок)
        for продолжение in цикл["продолжения"]:
            if продолжение is not None:
                self.связать(продолжение, заголовок)
        self.области.pop()
        self.текущая = None
        концы = list(цикл["выходы"])
        if выход_по_условию is not None:
            self.текущая = выход_по_условию
            self.закрыть_область(область, узел, "условие")
            концы.append(self.текущая)
        self.слить(концы, узел)

    def элемент_перебора(self, тип, узел):
        if isinstance(тип, Срез):
            return Ссылка(узел.изм and тип.изм, тип.регион, тип.элемент)
        if isinstance(тип, Составной):
            if тип.объявление.имя == "Диапазон":
                return тип.типы[0] if тип.типы else Неизвестный("диапазон")
            методы = тип.объявление.методы
            if "след" in методы:
                результат = self.результат_метода(методы["след"], тип)
                if isinstance(результат, Опц):
                    return результат.внутр
                return результат
        if isinstance(тип, Простой):
            return тип
        self.заметить(узел, f"перебор {показать(тип)}")
        return Неизвестный("элемент")

    def результат_метода(self, функция, тип_получателя):
        self.п.заголовок(функция)
        θ = {}
        for регион in функция.регионы_сигнатуры:
            θ[регион] = переменная("θ", None)
        типы = {}
        получатель = функция.параметры[0].тип
        цель = получатель.цель if isinstance(получатель, Ссылка) else получатель
        if isinstance(цель, Составной) and isinstance(тип_получателя, Составной):
            for шаблон, тип in zip(цель.типы, тип_получателя.типы):
                if isinstance(шаблон, ПараметрТипа):
                    типы[шаблон.имя] = тип
            for шаблон, регион in zip(цель.регионы_объекта, тип_получателя.регионы_объекта):
                θ[шаблон] = регион
        for большой, малый, _ in функция.контракт:
            б = θ.get(большой, большой)
            м = θ.get(малый, малый)
            if б in тип_получателя.регионы() and м.вид == "переменная":
                θ[малый] = б
            elif м in тип_получателя.регионы() and б.вид == "переменная":
                θ[большой] = м
        return функция.результат.заменить(θ, типы)

    def привязать_образец_перебора(self, образец, знач):
        if образец.вид == "образец_любой":
            return
        if образец.вид == "образец_имя":
            self.связать_значение(образец.путь[0], False, знач, образец)
            return
        if образец.вид == "образец_кортеж":
            типы = знач.тип.элементы if isinstance(знач.тип, Кортеж) else [Неизвестный("")] * len(образец.элементы)
            for элемент, тип in zip(образец.элементы, типы):
                self.привязать_образец_перебора(элемент, Знач(тип, элемент, знач.начало, отслеживаемое=знач.отслеживаемое))

    def регион(self, узел):
        блок = Регион("блок", узел.имя or "регион блока", узел, концы=[], точки=set(), внешние=[
            область.регион for область in self.области if область.регион is not None
        ], глубина=len(self.области))
        self.блоки.append(блок)
        if узел.устройство is not None:
            self.вычислить(узел.устройство)
        self.точка("начало_региона", узел, регион=блок)
        self.контексты.append(блок)
        self.блок(узел.тело, "регион", блок)
        self.контексты.pop()

    def через(self, узел):
        знач = None
        место = self.место(узел.значение)
        if место is not None:
            self.проверить_запись(место, узел.значение, "`через` занимает исключительно")
        if место is not None and место.корень is not None:
            self.точка("занять_рег", узел.значение, место=место)
        регион = None
        капсула_места = getattr(место, "капсула", None) if место is not None else None
        if капсула_места is not None:
            база, _ = капсула_места
            регион = регион_капсулы(база.тип) or self.новая_капсула(база.описание(), узел)
        elif место is not None and isinstance(место.тип, РегЗначение):
            регион = место.корень.рег if место.корень is not None and not место.путь else None
            регион = регион or место.тип.регион
        elif место is not None and isinstance(место.тип, Ссылка) and isinstance(место.тип.цель, РегЗначение):
            регион = место.тип.цель.регион
        if регион is None:
            self.заметить(узел, "через не по региону")
            регион = Регион("значение", "?", узел, концы=[])
        self.контексты.append(регион)
        self.блок(узел.тело, "через")
        self.контексты.pop()
        if место is not None and место.корень is not None and self.текущая is not None:
            self.точка("читать", узел.значение, место=место)

    def отложить(self, узел):
        потребляемые = self.потребляемые(узел.значение)
        self.точка("отложить", узел, привязки=потребляемые, выражение=узел.значение)
        self.области[-1].отложенные.append(узел.значение)

    def потребляемые(self, выражение):
        итог = []
        if выражение.вид == "вызов" and выражение.функция.вид == "поле":
            получатель = выражение.функция.объект
            if получатель.вид == "имя":
                привязка = self.найти_привязку(получатель.имя)
                if привязка is not None and (привязка.линейная or isinstance(привязка.тип, РегЗначение)):
                    функция = self.п.методы_типа(привязка.тип).get(выражение.функция.имя)
                    if функция is not None:
                        self.п.заголовок(функция)
                        if функция.параметры and функция.параметры[0].форма == "сам":
                            итог.append(привязка)
        if выражение.вид == "вызов":
            for аргумент in выражение.аргументы:
                if аргумент.вид == "имя":
                    привязка = self.найти_привязку(аргумент.имя)
                    if привязка is not None and привязка.линейная:
                        итог.append(привязка)
        return итог

    def запуск(self, узел):
        вызов = узел.значение
        if вызов.вид != "вызов":
            self.заметить(узел, "запуск не вызова")
            self.вычислить(вызов)
            return
        self.в_запуске = True
        знач = self.вычислить(вызов, режим="запуск")
        self.в_запуске = False
        self.точка("запуск", узел)

    def разрешить_тип(self, узел, роль="привязка"):
        область = ОбластьТипов(self.модуль, dict(self.подстановка_типов), None)
        try:
            return self.п.разрешить_тип(узел, область, lambda р, м, у: переменная(роль, у))
        except ОшибкаПрограммы as ошибка:
            self.заметить(узел, f"тип: {ошибка}")
            return Неизвестный("тип")

    def вычислить_для_сопоставления(self, узел):
        if узел.вид in ("имя", "поле", "индекс") or (узел.вид == "префикс" and узел.оп == "*"):
            место = self.место(узел)
            if место is not None:
                if место.корень is not None:
                    self.точка("читать", узел, место=место)
                return Знач(место.тип, узел, self.номер_текущей(), место=место,
                            отслеживаемое=место.корень.отслеживает if место.корень is not None and not место.путь else False,
                            только_чтение=место.только_чтение)
        return self.вычислить(узел)

    def привязки_образца(self, образец, знач, узел):
        итог = []
        self.собрать_привязки(образец, знач.тип, знач, итог, режим=self.режим_сопоставления(знач))
        return итог

    def режим_сопоставления(self, знач):
        if isinstance(знач.тип, Ссылка):
            if знач.отслеживаемое and знач.тип.изм:
                return ("ссылка", знач.тип.регион, True)
            if линейный(знач.тип.цель):
                return ("ссылка", знач.тип.регион, знач.тип.изм)
            return ("копия_чтение", знач.тип.регион, False)
        if знач.место is not None and not знач.место.отслеживается:
            return ("копия_чтение", знач.место.регион, False)
        if знач.место is not None:
            return ("значение_места", None, False)
        return ("значение", None, False)

    def собрать_привязки(self, образец, тип, знач, итог, режим, верхний=True):
        вид = образец.вид
        if верхний:
            while isinstance(тип, Ссылка):
                тип = тип.цель
        if вид in ("образец_любой", "образец_литерал"):
            return
        if вид == "образец_или":
            for альтернатива in образец.альтернативы:
                self.собрать_привязки(альтернатива, тип, знач, итог, режим, верхний=False)
            return
        if вид == "образец_изм":
            итог.append((образец.имя, self.знач_привязки(тип, знач, образец, режим), True))
            return
        if вид == "образец_кортеж":
            типы = тип.элементы if isinstance(тип, Кортеж) else [Неизвестный("")] * len(образец.элементы)
            for элемент, тип_элемента in zip(образец.элементы, типы):
                self.собрать_привязки(элемент, тип_элемента, знач, итог, режим, верхний=False)
            return
        if вид == "образец_имя":
            if len(образец.путь) == 1 and ведущая_строчная(образец.путь[0]) and образец.аргументы is None and образец.поля is None:
                итог.append((образец.путь[0], self.знач_привязки(тип, знач, образец, режим), False))
                return
            имя_варианта = образец.путь[-1]
            поля = self.поля_варианта(тип, имя_варианта)
            if образец.аргументы is not None:
                for номер, (метка, подобразец) in enumerate(образец.аргументы):
                    тип_поля = поля[номер] if номер < len(поля) else Неизвестный("поле")
                    self.собрать_привязки(подобразец, тип_поля, знач, итог, режим, верхний=False)
            if образец.поля is not None and isinstance(тип, Составной):
                for имя, подобразец, токен in образец.поля:
                    тип_поля = тип.поле(имя) or Неизвестный("поле")
                    if подобразец is None:
                        итог.append((имя, self.знач_привязки(тип_поля, знач, образец, режим), False))
                    else:
                        self.собрать_привязки(подобразец, тип_поля, знач, итог, режим, верхний=False)

    def поля_варианта(self, тип, имя):
        if isinstance(тип, Опц):
            return [тип.внутр] if имя == "Есть" else []
        if isinstance(тип, Составной):
            поля = тип.вариант(имя)
            if поля is not None:
                return [поле for _, поле in поля]
        return []

    def знач_привязки(self, тип, знач, образец, режим):
        вид, регион, изм = режим
        if вид == "ссылка":
            новый = Знач(Ссылка(изм, регион, тип), образец, знач.начало, отслеживаемое=True)
            return новый
        if вид == "копия_чтение":
            копия = Знач(тип, образец, знач.начало, только_чтение=содержит_изменяемое(тип))
            копия.из_копии = True
            return копия
        return Знач(тип, образец, знач.начало, место=знач.место if линейный(тип) else None)

    def место(self, узел):
        вид = узел.вид
        if вид == "скобки":
            return self.место(узел.значение)
        if вид == "имя":
            привязка = self.найти_привязку(узел.имя)
            if привязка is None:
                return self.временное_место(узел)
            if привязка.захват is not None:
                self.отметить_захват(привязка, "чтение")
                self.точка("читать", узел, место=Место(привязка, (), привязка.тип, True, None, False, узел))
                цель = привязка.тип.цель
                return Место(привязка, (("разыменование",),), цель, False, привязка.захват, привязка.изм_снаружи, узел,
                             [привязка.захват])
            return Место(привязка, (), привязка.тип, True, None, привязка.изм, узел, (), привязка.только_чтение)
        if вид == "поле":
            if self.путь_не_значение(узел.объект):
                return self.временное_место(узел)
            база = self.место(узел.объект)
            if база is None:
                return None
            база = self.разыменовать_место(база, узел.объект)
            тип = база.тип
            тип_поля = self.тип_поля(тип, узел.имя, узел)
            путь = база.путь + (("поле", узел.имя),)
            if капсульные_регионы(тип_поля):
                опора = база.регионы_пути[-1] if база.регионы_пути else None
                тип_поля = self.капсулы_места(база, путь, тип_поля, узел, опора)
            место = Место(база.корень, путь, тип_поля, база.отслеживается, база.регион,
                          база.запись, узел, база.регионы_пути, база.только_чтение, база.через_общую)
            if isinstance(тип, Составной) and getattr(тип.объявление, "поле_рег", None) == узел.имя:
                место.капсула = (база, тип.объявление)
            return место
        if вид == "индекс":
            if узел.индекс.вид == "диапазон":
                return self.временное_место(узел)
            self.вычислить(узел.индекс)
            база = self.место(узел.объект)
            if база is None:
                return None
            база = self.разыменовать_место(база, узел.объект)
            тип = база.тип
            if isinstance(тип, Массив):
                return Место(база.корень, база.путь + (("индекс",),), тип.элемент, база.отслеживается, база.регион,
                             база.запись, узел, база.регионы_пути, база.только_чтение, база.через_общую)
            if isinstance(тип, Составной) and тип.объявление.имя == "Массив" and тип.объявление.модуль is self.п.прелюдия:
                буфер = тип.поле("элементы")
                if isinstance(буфер, Срез):
                    if база.корень is not None:
                        self.точка("читать", узел.объект, место=база)
                    return Место(база.корень, база.путь + (("поле", "элементы"), ("срез",), ("индекс",)), буфер.элемент,
                                 False, буфер.регион, буфер.изм and not база.через_общую, узел,
                                 база.регионы_пути + [буфер.регион], база.только_чтение,
                                 база.через_общую or not буфер.изм)
            if isinstance(тип, Срез):
                if база.корень is not None:
                    self.точка("читать", узел.объект, место=база)
                return Место(база.корень, база.путь + (("срез",), ("индекс",)), тип.элемент, False, тип.регион,
                             тип.изм, узел, база.регионы_пути + [тип.регион], база.только_чтение, not тип.изм)
            self.заметить(узел, f"индекс {показать(тип)}")
            return Место(None, (), Неизвестный("индекс"), False, None, True, узел)
        if вид == "префикс" and узел.оп == "*":
            база = self.место(узел.операнд)
            if база is None:
                return None
            return self.разыменовать_место(база, узел.операнд, явно=True)
        return self.временное_место(узел)

    def путь_не_значение(self, узел):
        if узел.вид == "имя":
            if self.найти_привязку(узел.имя) is not None:
                return False
            return узел.имя in self.модуль.подключения or self.найти_тип(узел.имя) is not None
        if узел.вид == "вызов":
            return self.путь_не_значение(узел.функция) and self.похоже_на_тип(узел)
        if узел.вид == "поле":
            return self.путь_не_значение(узел.объект) and not self.это_функция_модуля(узел)
        return False

    def это_функция_модуля(self, узел):
        if узел.объект.вид == "имя" and узел.объект.имя in self.модуль.подключения and self.найти_привязку(узел.объект.имя) is None:
            цель = self.модуль.подключения[узел.объект.имя]
            return узел.имя in цель.функции or узел.имя in цель.константы
        return False

    def похоже_на_тип(self, узел):
        try:
            return self.п.похоже_на_тип(узел, self.модуль)
        except ОшибкаПрограммы:
            return False

    def найти_тип(self, имя):
        return self.модуль.типы.get(имя) or self.п.прелюдия.типы.get(имя)

    def временное_место(self, узел):
        знач = self.вычислить(узел)
        if знач is None:
            return None
        if знач.место is not None:
            return знач.место
        привязка = Привязка("временное", знач.тип, True, узел, self.области[-1], временная=True)
        привязка.отслеживает = знач.отслеживаемое
        if isinstance(знач.тип, РегЗначение):
            привязка.рег = знач.тип.регион
        self.учесть(привязка)
        self.держать(знач, self.точка("определить", узел, привязка=привязка, знач=знач))
        return Место(привязка, (), знач.тип, True, None, True, узел)

    def разыменовать_место(self, база, узел, явно=False):
        тип = база.тип
        if not isinstance(тип, Ссылка):
            if явно:
                self.заметить(узел, f"разыменование {показать(тип)}")
            return база
        while isinstance(тип, Ссылка):
            if база.корень is not None:
                self.точка("читать", узел, место=база, сквозное=True)
            отслеживается = линейный(тип.цель) and база.корень is not None
            цепочка = база.регионы_пути + [тип.регион]
            путь = база.путь + (("разыменование",),)
            цель = тип.цель
            if капсульные_регионы(цель):
                цель = self.капсулы_места(база, путь, цель, узел, тип.регион)
            база = Место(база.корень, путь, цель, отслеживается, тип.регион, тип.изм, узел,
                         цепочка, база.только_чтение or (not тип.изм and False), база.через_общую or not тип.изм)
            тип = цель
        return база

    def тип_поля(self, тип, имя, узел):
        if isinstance(тип, Составной):
            поле = тип.поле(имя)
            if поле is not None:
                return поле
        if isinstance(тип, (Срез, Массив)) and имя == "длина":
            return РАЗМ
        if isinstance(тип, Простой) and тип.имя.startswith("вектор") and имя in ("х", "у", "з"):
            return Простой(тип.имя.split("/")[1] if "/" in тип.имя else "в32")
        if isinstance(тип, Простой):
            return Простой("поле")
        self.заметить(узел, f"поле {имя} у {показать(тип)}")
        return Неизвестный("поле")

    def примечание_закрепления(self, тип):
        while not (isinstance(тип, Составной) and getattr(тип.объявление, "закреплённый_явно", False)):
            if isinstance(тип, Составной):
                поля = [тип.поле(имя) for имя in тип.объявление.поля]
                поля += [поле for имя in тип.объявление.варианты for _, поле in тип.вариант(имя)]
                следующее = next((поле for поле in поля if закреплённый(поле)), None)
            elif isinstance(тип, Опц):
                следующее = тип.внутр
            elif isinstance(тип, Массив):
                следующее = тип.элемент
            else:
                следующее = None
            if следующее is None:
                return []
            тип = следующее
        объявление = тип.объявление
        токен = getattr(объявление.узел, "токен_имени", None)
        if токен is None or объявление.модуль is not self.модуль:
            return []
        return [(токен, f"тип `{объявление.имя}` закреплён", объявление.модуль)]

    def перезапись_капсулы_по_ссылке(self, место, узел):
        self.ошибка(узел, "С0418", f"капсула `{место.описание()}` перезаписана через ссылку вместе со своим полем `Рег`: "
                    f"ссылки в её арену пережили бы её; целиком капсулу меняет только владелец места")

    def нарушить_капсулу(self, место, узел, действие):
        капсула = getattr(место, "капсула", None)
        if капсула is None:
            return место
        база, объявление = капсула
        self.ошибка(узел, "С0418", f"поле `{объявление.поле_рег}` капсулы `{объявление.имя}` {действие}: "
                    f"иначе поля пережили бы свою арену; капсулу потребляют целиком")
        return база

    def прочитать(self, место, узел, режим="значение"):
        if режим == "значение":
            место = self.нарушить_капсулу(место, узел, "перемещено отдельно")
        тип = место.тип
        if режим == "значение" and закреплённый(тип):
            self.ошибка(узел, "С0420", f"закреплённое значение `{место.описание()}` нельзя переместить или скопировать: "
                        f"его адрес мог где-то сохраниться; передают ссылку, новое создают на месте",
                        self.примечание_закрепления(тип))
        только_чтение = место.только_чтение or (место.через_общую and содержит_изменяемое(тип))
        отслеживаемое = False
        if место.корень is not None and not место.путь:
            отслеживаемое = место.корень.отслеживает
        if режим == "значение" and (линейный(тип) or isinstance(тип, РегЗначение)):
            точка = self.точка("переместить", узел, место=место, запуск=getattr(self, "в_запуске", False))
            self.закончить_капсулы(место, точка)
            if place_root_capture(место):
                self.отметить_захват(место.корень, "перемещение")
            if isinstance(тип, РегЗначение) and место.корень is not None:
                регион = место.корень.рег
                if регион is not None and getattr(self, "в_запуске", False) is False:
                    pass
        else:
            точка = self.точка("читать", узел, место=место)
        return Знач(тип, узел, точка.номер, место=место, отслеживаемое=отслеживаемое, только_чтение=только_чтение)

    def вычислить(self, узел, ожидаемый=None, режим="значение", изм=False):
        try:
            return self._вычислить(узел, ожидаемый, режим, изм)
        except Неподдержано as причина:
            self.заметить(узел, str(причина))
            return Знач(Неизвестный(str(причина)), узел, self.номер_текущей())

    def _вычислить(self, узел, ожидаемый, режим, изм):
        вид = узел.вид
        if self.текущая is None and вид not in ("замыкание",):
            self.текущая = None
        if вид == "лит":
            return self.литерал(узел, ожидаемый)
        if вид == "скобки":
            return self.вычислить(узел.значение, ожидаемый, режим, изм)
        if вид == "имя":
            return self.имя(узел, ожидаемый, режим, изм)
        if вид == "поле":
            return self.значение_поля(узел, ожидаемый, режим, изм)
        if вид == "индекс":
            return self.индекс(узел, ожидаемый, режим, изм)
        if вид == "вызов":
            return self.вызов(узел, ожидаемый, режим)
        if вид == "ссылка":
            return self.ссылка(узел, ожидаемый)
        if вид == "префикс":
            return self.префикс(узел, ожидаемый, режим)
        if вид == "бинарное":
            return self.бинарное(узел, ожидаемый)
        if вид in ("сравнение", "принадлежность", "логическое", "не"):
            return self.логика(узел)
        if вид == "это":
            знач = self.вычислить_для_сопоставления(узел.значение)
            точка = self.точка("проверка", узел)
            self.держать(знач, точка)
            return Знач(БУЛ, узел, точка.номер)
        if вид == "как":
            знач = self.вычислить(узел.значение)
            точка = self.точка("использовать", узел)
            self.держать(знач, точка)
            тип = self.разрешить_тип(узел.тип, "как")
            return Знач(тип, узел, точка.номер)
        if вид == "диапазон":
            тип_границ = Неизвестный("граница")
            for граница in (узел.от, узел.до):
                if граница is not None:
                    знач = self.вычислить(граница)
                    тип_границ = знач.тип
            диапазон = self.п.прелюдия.типы["Диапазон"]
            return Знач(Составной(диапазон, [тип_границ], []), узел, self.номер_текущей())
        if вид == "литерал":
            return self.составной_литерал(узел, ожидаемый)
        if вид == "кортеж":
            ожидаемые = ожидаемый.элементы if isinstance(ожидаемый, Кортеж) else [None] * len(узел.элементы)
            значения = [self.вычислить(элемент, ож) for элемент, ож in zip(узел.элементы, ожидаемые)]
            точка = self.точка("использовать", узел)
            for знач in значения:
                self.держать(знач, точка)
            return Знач(Кортеж([знач.тип for знач in значения]), узел, точка.номер,
                        отслеживаемое=any(знач.отслеживаемое for знач in значения))
        if вид == "выбор":
            return self.выбор(узел, ожидаемый, режим)
        if вид == "замыкание":
            return self.замыкание(узел, ожидаемый)
        if вид == "вместе":
            return self.вместе(узел, ожидаемый)
        if вид == "заглушка":
            return Знач(Неизвестный("_"), узел, self.номер_текущей())
        if вид in ("тип_массив", "тип_срез", "опц", "дин", "сырой", "тип_функции", "тип_структ", "тип_переч", "тип_набор"):
            return Знач(Значение_типа(self.разрешить_тип(узел, "тип")), узел, self.номер_текущей())
        if вид == "асм":
            for _, _, выражение in узел.операнды:
                self.вычислить(выражение)
            return Знач(ПУСТО, узел, self.номер_текущей())
        raise Неподдержано(f"выражение {вид}")

    def литерал(self, узел, ожидаемый):
        if узел.вид_лит == "СТРОКА":
            return Знач(Срез(False, СТАТИЧ, Н8, строка=True), узел, self.номер_текущей())
        if узел.вид_лит == "БУЛ":
            return Знач(БУЛ, узел, self.номер_текущей())
        if узел.вид_лит in ("СИМВОЛ",):
            return Знач(СИМ, узел, self.номер_текущей())
        if узел.вид_лит == "БАЙТ":
            return Знач(Н8, узел, self.номер_текущей())
        if isinstance(ожидаемый, Простой):
            return Знач(ожидаемый, узел, self.номер_текущей())
        return Знач(Простой("ц64" if узел.вид_лит == "ЦЕЛОЕ" else "в64"), узел, self.номер_текущей())

    def имя(self, узел, ожидаемый, режим, изм):
        привязка = self.найти_привязку(узел.имя)
        if привязка is not None:
            место = self.место(узел)
            if режим == "перебор":
                return self.источник_перебора(место, узел, изм)
            return self.прочитать(место, узел, "значение" if режим in ("значение", "запуск") else "чтение")
        return self.глобальное_значение(узел.имя, узел, ожидаемый, self.модуль)

    def глобальное_значение(self, имя, узел, ожидаемый, модуль):
        if имя in модуль.константы:
            return self.значение_константы(модуль.константы[имя], узел)
        if имя in модуль.функции:
            return Знач(Вызываемое([модуль.функции[имя]]), узел, self.номер_текущей())
        тип = модуль.типы.get(имя) or (self.п.прелюдия.типы.get(имя) if модуль is self.модуль else None)
        if тип is not None:
            return Знач(Значение_типа(self.п.экземпляр(тип, [], ОбластьТипов(модуль), lambda р, м, у: переменная("тип", у), False)), узел, self.номер_текущей())
        if модуль is self.модуль and имя in модуль.подключения:
            return Знач(Модуль_как_значение(модуль.подключения[имя]), узел, self.номер_текущей())
        if модуль is self.модуль and имя in self.подстановка_типов:
            return Знач(Значение_типа(self.подстановка_типов[имя]), узел, self.номер_текущей())
        if модуль is self.модуль and (имя in ПРОСТЫЕ or имя in ("стр", "Вектор")):
            if имя == "Вектор":
                return Знач(Значение_типа(Простой("вектор")), узел, self.номер_текущей())
            if имя == "стр":
                return Знач(Значение_типа(Срез(False, переменная("тип", узел), Н8, строка=True)), узел, self.номер_текущей())
            return Знач(Значение_типа(Простой(имя)), узел, self.номер_текущей())
        вариант = self.найти_вариант(имя, ожидаемый, модуль)
        if вариант is not None:
            return self.значение_варианта(вариант, имя, [], узел)
        raise Неподдержано(f"неизвестное имя {имя}")

    def значение_константы(self, константа, узел):
        псевдоним = self.п.константа_как_тип(константа)
        if псевдоним is not None:
            return Знач(Значение_типа(self.п.освежить_псевдоним(псевдоним, lambda р, м, у: переменная("тип", у), узел)), узел, self.номер_текущей())
        if константа.тип is None:
            if константа.узел.тип is not None:
                константа.тип = self.п.разрешить_тип(константа.узел.тип, ОбластьТипов(константа.модуль), lambda р, м, у: СТАТИЧ)
            else:
                константа.тип = self.тип_константы(константа)
        тип = константа.тип
        return Знач(тип, узел, self.номер_текущей())

    def тип_константы(self, константа):
        значение = константа.узел.значение
        if значение.вид == "лит":
            if значение.вид_лит == "СТРОКА":
                return Срез(False, СТАТИЧ, Н8, строка=True)
            return Простой("число")
        if значение.вид == "вызов" and значение.функция.вид == "поле":
            объект = значение.функция.объект
            if объект.вид == "имя" and объект.имя in константа.модуль.подключения:
                цель = константа.модуль.подключения[объект.имя]
                функция = цель.функции.get(значение.функция.имя)
                if функция is not None:
                    self.п.заголовок(функция)
                    return функция.результат
        if значение.вид == "литерал" and значение.тип is not None:
            try:
                return self.п.разрешить_тип(значение.тип, ОбластьТипов(константа.модуль), lambda р, м, у: СТАТИЧ)
            except ОшибкаПрограммы:
                return Простой("константа")
        return Простой("константа")

    def найти_вариант(self, имя, ожидаемый, модуль):
        if isinstance(ожидаемый, Опц) and имя in ("Есть", "Ничего"):
            return ожидаемый
        if isinstance(ожидаемый, Составной) and имя in ожидаемый.объявление.варианты:
            return ожидаемый
        if имя in ("Есть", "Ничего"):
            return Опц(Неизвестный("опц"))
        if имя in ("Успех", "Ошибка"):
            итог = self.п.прелюдия.типы["Итог"]
            if isinstance(ожидаемый, Составной) and ожидаемый.объявление is итог:
                return ожидаемый
            return Составной(итог, [Неизвестный("т"), Неизвестный("о")], [])
        кандидаты = []
        for источник in [модуль] + list(модуль.подключения.values()):
            for объявление in источник.типы.values():
                if объявление.вид == "переч" and имя in объявление.варианты:
                    кандидаты.append(объявление)
        if isinstance(ожидаемый, Составной):
            for кандидат in кандидаты:
                if кандидат is ожидаемый.объявление:
                    return ожидаемый
            for поле in self.поля_итога(ожидаемый):
                if isinstance(поле, Составной) and имя in поле.объявление.варианты:
                    return поле
        if len(кандидаты) >= 1:
            объявление = кандидаты[0]
            return self.п.экземпляр(объявление, [], ОбластьТипов(объявление.модуль), lambda р, м, у: переменная("вариант", у), False)
        return None

    def поля_итога(self, тип):
        if isinstance(тип, Составной) and тип.объявление.имя == "Итог":
            return тип.типы
        return []

    def значение_варианта(self, тип, имя, аргументы, узел):
        if isinstance(тип, Опц):
            if имя == "Ничего":
                return Знач(тип, узел, self.номер_текущей())
            if аргументы:
                знач = self.вычислить(аргументы[0], тип.внутр if not isinstance(тип.внутр, Неизвестный) else None)
                if isinstance(тип.внутр, Неизвестный):
                    результат = Опц(self.освежить(знач.тип, узел, "есть"))
                    self.подтип(знач.тип, результат.внутр, аргументы[0])
                else:
                    результат = Опц(self.освежить(тип.внутр, узел, "есть"))
                    self.подтип(знач.тип, результат.внутр, аргументы[0])
                точка = self.точка("использовать", узел)
                self.держать(знач, точка)
                return Знач(результат, узел, точка.номер, отслеживаемое=знач.отслеживаемое)
            return Знач(тип, узел, self.номер_текущей())
        if isinstance(тип, Составной):
            поля = тип.вариант(имя) or []
            if тип.объявление.имя == "Итог" and any(isinstance(т, Неизвестный) for т in тип.типы):
                значения = [self.вычислить(аргумент) for аргумент in аргументы]
                типы = list(тип.типы)
                номер = 0 if имя == "Успех" else 1
                if значения:
                    типы[номер] = self.освежить(значения[0].тип, узел, "итог")
                    self.подтип(значения[0].тип, типы[номер], аргументы[0])
                elif номер == 0:
                    типы[0] = ПУСТО
                точка = self.точка("использовать", узел)
                for знач in значения:
                    self.держать(знач, точка)
                return Знач(Составной(тип.объявление, типы, []), узел, точка.номер,
                            отслеживаемое=any(знач.отслеживаемое for знач in значения))
            новый = self.освежить(тип, узел, "вариант")
            поля = новый.вариант(имя) or []
            значения = []
            for номер, аргумент in enumerate(аргументы):
                ожидание = поля[номер][1] if номер < len(поля) else None
                знач = self.вычислить(аргумент, ожидание)
                значения.append(знач)
                if ожидание is not None:
                    self.подтип(знач.тип, ожидание, аргумент, "поле", {"поле": имя})
            точка = self.точка("использовать", узел)
            for знач in значения:
                self.держать(знач, точка)
            return Знач(новый, узел, точка.номер, отслеживаемое=any(знач.отслеживаемое for знач in значения))
        raise Неподдержано(f"вариант {имя}")

    def источник_перебора(self, место, узел, изм):
        тип = место.тип
        if isinstance(тип, Массив):
            return self.занять(место, изм, узел, срез=True)
        if isinstance(тип, Срез):
            return self.прочитать(место, узел, "чтение")
        if isinstance(тип, Ссылка):
            цель = тип.цель
            if isinstance(цель, (Срез, Массив)):
                знач = self.прочитать(место, узел, "чтение")
                return Знач(Срез(тип.изм and изм, тип.регион, цель.элемент if isinstance(цель, Срез) else цель.элемент),
                            узел, знач.начало, отслеживаемое=знач.отслеживаемое)
            if isinstance(цель, Составной) and "итер" in цель.объявление.методы:
                return self.вызвать_метод(место, "итер", [], узел, None)
        if isinstance(тип, Составной):
            методы = тип.объявление.методы
            if "след" in методы:
                return self.прочитать(место, узел, "значение")
            if "итер" in методы:
                return self.вызвать_метод(место, "итер", [], узел, None)
        return self.прочитать(место, узел, "чтение")

    def значение_поля(self, узел, ожидаемый, режим, изм):
        объект = узел.объект
        if объект.вид == "имя" and self.найти_привязку(объект.имя) is None:
            if объект.имя in self.модуль.подключения:
                цель = self.модуль.подключения[объект.имя]
                return self.член_модуля(цель, узел.имя, узел, ожидаемый)
            тип = self.найти_тип(объект.имя)
            if тип is not None:
                экземпляр = self.п.экземпляр(тип, [], ОбластьТипов(тип.модуль), lambda р, м, у: переменная("тип", у), False)
                return self.член_типа(экземпляр, узел.имя, узел, ожидаемый)
            if объект.имя in self.модуль.константы:
                псевдоним = self.п.константа_как_тип(self.модуль.константы[объект.имя])
                if псевдоним is not None:
                    return self.член_типа(псевдоним, узел.имя, узел, ожидаемый)
            if объект.имя in ПРОСТЫЕ or объект.имя == "стр":
                встроенный = Срез(False, СТАТИЧ, Н8, строка=True) if объект.имя == "стр" else Простой(объект.имя)
                return self.член_типа(встроенный, узел.имя, узел, ожидаемый)
        if self.путь_не_значение(объект):
            база = self.вычислить(объект)
            if isinstance(база.тип, Модуль_как_значение):
                return self.член_модуля(база.тип.модуль, узел.имя, узел, ожидаемый)
            if isinstance(база.тип, Значение_типа):
                return self.член_типа(база.тип.тип, узел.имя, узел, ожидаемый)
        место = self.место(узел)
        if место is None:
            return Знач(Неизвестный("поле"), узел, self.номер_текущей())
        if режим == "перебор":
            return self.источник_перебора(место, узел, изм)
        return self.прочитать(место, узел, "значение" if режим in ("значение", "запуск") else "чтение")

    def член_модуля(self, модуль, имя, узел, ожидаемый):
        if имя in модуль.функции:
            return Знач(Вызываемое([модуль.функции[имя]]), узел, self.номер_текущей())
        if имя in модуль.константы:
            return self.значение_константы(модуль.константы[имя], узел)
        if имя in модуль.типы:
            тип = модуль.типы[имя]
            return Знач(Значение_типа(self.п.экземпляр(тип, [], ОбластьТипов(модуль), lambda р, м, у: переменная("тип", у), False)), узел, self.номер_текущей())
        if имя in модуль.подключения:
            return Знач(Модуль_как_значение(модуль.подключения[имя]), узел, self.номер_текущей())
        raise Неподдержано(f"нет {имя} в {модуль.имя}")

    def член_типа(self, тип, имя, узел, ожидаемый):
        if isinstance(тип, Составной):
            if имя in тип.объявление.методы:
                return Знач(Вызываемое([тип.объявление.методы[имя]], владелец=тип), узел, self.номер_текущей())
            if имя in тип.объявление.варианты:
                return self.значение_варианта(тип, имя, [], узел)
        if isinstance(тип, Простой) or (isinstance(тип, Срез) and тип.строка):
            методы = self.п.методы_типа(тип)
            if имя in методы:
                return Знач(Вызываемое([методы[имя]], владелец=тип), узел, self.номер_текущей())
        raise Неподдержано(f"нет {имя} у типа {показать(тип)}")

    def индекс(self, узел, ожидаемый, режим, изм):
        if узел.индекс.вид == "диапазон":
            return self.срез(узел, ожидаемый)
        место = self.место(узел)
        if место is None:
            return Знач(Неизвестный("индекс"), узел, self.номер_текущей())
        return self.прочитать(место, узел, "значение" if режим in ("значение", "запуск") else "чтение")

    def срез(self, узел, ожидаемый, изм_явно=None):
        диапазон = узел.индекс
        for граница in (диапазон.от, диапазон.до):
            if граница is not None:
                self.вычислить(граница)
        if self.путь_не_значение(узел.объект):
            raise Неподдержано("срез типа")
        база = self.место(узел.объект)
        if база is None:
            return Знач(Неизвестный("срез"), узел, self.номер_текущей())
        база = self.разыменовать_место(база, узел.объект)
        тип = база.тип
        if изм_явно is not None:
            изм = изм_явно
        elif isinstance(ожидаемый, Срез):
            изм = ожидаемый.изм
        else:
            изм = (база.запись and not база.только_чтение and not (isinstance(тип, Срез) and not тип.изм)) if not isinstance(ожидаемый, Срез) else False
        if isinstance(тип, Массив):
            return self.занять(база, изм, узел, срез=True)
        if isinstance(тип, Срез):
            знач = self.прочитать(база, узел.объект, "чтение")
            if изм and not тип.изм:
                if isinstance(ожидаемый, Срез) and ожидаемый.изм:
                    self.ошибка(узел, "С0406", "изменяемый срез из среза для чтения")
                изм = False
            return Знач(Срез(изм, тип.регион, тип.элемент, тип.строка), узел, знач.начало, отслеживаемое=знач.отслеживаемое)
        raise Неподдержано(f"срез {показать(тип)}")

    def ссылка(self, узел, ожидаемый):
        операнд = узел.операнд
        if self.путь_не_значение(операнд) and операнд.вид in ("имя", "поле", "вызов"):
            знач = self.вычислить(операнд)
            if isinstance(знач.тип, Значение_типа):
                return Знач(Значение_типа(Ссылка(узел.изм, переменная("тип", узел), знач.тип.тип)), узел, знач.начало)
        место = self.место(операнд)
        if место is None:
            return Знач(Неизвестный("ссылка"), узел, self.номер_текущей())
        return self.занять(место, узел.изм, узел)

    def занять(self, место, изм, узел, срез=False):
        if изм:
            self.проверить_запись(место, узел)
            self.нарушить_капсулу(место, узел, "занято через `&изм` вне `через`")
        if место.корень is not None and место.корень.захват is not None:
            self.отметить_захват(место.корень, "запись" if изм else "чтение")
        тип_цели = место.тип
        if срез and isinstance(тип_цели, Массив):
            построить = lambda регион: Срез(изм, регион, тип_цели.элемент)
        else:
            построить = lambda регион: Ссылка(изм, регион, тип_цели)
        if место.отслеживается and место.корень is not None:
            заём = Регион("заём", место.описание(), узел, место=место, изм=изм, точка=None)
            точка = self.точка("занять", узел, заём=заём, место=место)
            заём.точка = точка.номер
            self.заёмы.append(заём)
            for регион in место.регионы_пути:
                self.ограничение(регион, заём, узел, "перезаём")
            return Знач(построить(заём), узел, точка.номер, отслеживаемое=True)
        регион = место.регион if место.регион is not None else переменная("место", узел)
        точка = self.точка("читать", узел, место=место) if место.корень is not None else self.точка("использовать", узел)
        return Знач(построить(регион), узел, точка.номер)

    def префикс(self, узел, ожидаемый, режим):
        оп = узел.оп
        if оп == "попытка":
            return self.попытка(узел, ожидаемый)
        if оп == "*":
            место = self.место(узел)
            if место is None:
                return Знач(Неизвестный("*"), узел, self.номер_текущей())
            return self.прочитать(место, узел, "значение" if режим == "значение" else "чтение")
        if оп in ("опасно", "компил"):
            return self.вычислить(узел.операнд, ожидаемый, режим)
        знач = self.вычислить(узел.операнд, ожидаемый)
        точка = self.точка("использовать", узел)
        self.держать(знач, точка)
        return Знач(знач.тип if isinstance(знач.тип, Простой) else Простой("число"), узел, точка.номер)

    def попытка(self, узел, ожидаемый):
        знач = self.вычислить(узел.операнд)
        тип = знач.тип
        успех = Неизвестный("попытка")
        if isinstance(тип, Составной) and тип.объявление.имя == "Итог":
            успех = тип.типы[0]
        elif isinstance(тип, Опц):
            успех = тип.внутр
        ветвление = self.точка("проверка", узел)
        self.держать(знач, ветвление)
        self.точка("выход", узел, форма="попытка", якорь="попытка")
        self.выйти_до(self.области[0], узел, "попытка")
        self.выходы_функции.append(self.текущая)
        self.текущая = ветвление
        точка = self.точка("ветвь", узел)
        return Знач(успех, узел, точка.номер, место=знач.место if линейный(успех) else None,
                    отслеживаемое=знач.отслеживаемое, только_чтение=знач.только_чтение)

    def бинарное(self, узел, ожидаемый):
        левый = self.вычислить(узел.левый, ожидаемый if isinstance(ожидаемый, Простой) else None, режим="чтение")
        правый = self.вычислить(узел.правый, левый.тип if isinstance(левый.тип, Простой) else None, режим="чтение")
        точка = self.точка("использовать", узел)
        self.держать(левый, точка)
        self.держать(правый, точка)
        if isinstance(левый.тип, Составной):
            типаж = {"+": "Сложение", "-": "Вычитание", "*": "Умножение"}.get(узел.оп)
            имя = {"+": "сложить", "-": "вычесть", "*": "умножить"}.get(узел.оп)
            функция = левый.тип.объявление.методы.get(имя) if имя else None
            if функция is not None:
                self.п.заголовок(функция)
                return Знач(функция.результат, узел, точка.номер)
        if узел.оп in ("+?", "-?", "*?"):
            тип = левый.тип.внутр if isinstance(левый.тип, Опц) else левый.тип
            return Знач(Опц(тип), узел, точка.номер)
        тип = левый.тип if isinstance(левый.тип, Простой) and левый.тип.имя != "число" else правый.тип
        if not isinstance(тип, Простой):
            тип = Простой("число")
        return Знач(тип, узел, точка.номер)

    def логика(self, узел):
        вид = узел.вид
        if вид == "не":
            знач = self.вычислить(узел.операнд, режим="чтение")
            точка = self.точка("использовать", узел)
            self.держать(знач, точка)
            return Знач(БУЛ, узел, точка.номер)
        if вид == "логическое":
            истина, ложь, _ = self.условие(узел)
            self.слить([истина, ложь], узел)
            return Знач(БУЛ, узел, self.номер_текущей())
        левый = self.вычислить(узел.левый, режим="чтение")
        правый = self.вычислить(узел.правый, левый.тип if isinstance(левый.тип, Простой) else None, режим="чтение")
        точка = self.точка("использовать", узел)
        self.держать(левый, точка)
        self.держать(правый, точка)
        return Знач(БУЛ, узел, точка.номер)

    def составной_литерал(self, узел, ожидаемый):
        тип_узел = узел.тип
        тип = None
        if тип_узел is not None:
            значение_типа = self.вычислить(тип_узел)
            if isinstance(значение_типа.тип, Значение_типа):
                тип = значение_типа.тип.тип
            else:
                тип = Неизвестный("литерал")
        if isinstance(тип, Составной):
            новый = self.освежить(тип, узел, "литерал")
            упаковка = None
            if регион_капсулы(новый) is not None:
                упаковка = self.новая_капсула(f"{новый.объявление.имя}{{…}}", узел)
                новый = Составной(новый.объявление, новый.типы, [упаковка] + новый.регионы_объекта[1:])
            значения = []
            арена_рег = None
            for метка, значение, _ in узел.элементы:
                имя_поля = метка or (значение.имя if значение.вид == "имя" else None)
                тип_поля = новый.поле(имя_поля) if имя_поля else None
                знач = self.вычислить(значение, тип_поля)
                значения.append(знач)
                if упаковка is not None and имя_поля == новый.объявление.поле_рег and isinstance(знач.тип, РегЗначение):
                    корень = знач.место.корень if знач.место is not None else None
                    арена_рег = (корень.рег if корень is not None and корень.рег is not None else None) or знач.тип.регион
                    continue
                if тип_поля is not None:
                    self.подтип(знач.тип, тип_поля, значение, "поле", {"поле": имя_поля, "тип": новый})
            точка = self.точка("использовать", узел)
            for знач in значения:
                self.держать(знач, точка)
            if упаковка is not None and арена_рег is not None:
                упаковка.источник = арена_рег
                if getattr(арена_рег, "концы", None) is not None:
                    конец = self.точка("поглотить_регион", узел, регион=арена_рег)
                    арена_рег.концы.append(конец.номер)
                    точка = конец
            return Знач(новый, узел, точка.номер, отслеживаемое=any(з.отслеживаемое for з in значения))
        элемент = тип.элемент if isinstance(тип, Массив) else None
        значения = [self.вычислить(значение, элемент) for _, значение, _ in узел.элементы]
        точка = self.точка("использовать", узел)
        for знач in значения:
            self.держать(знач, точка)
        return Знач(тип if тип is not None else Неизвестный("литерал"), узел, точка.номер)

    def выбор(self, узел, ожидаемый, режим):
        знач = self.вычислить_для_сопоставления(узел.значение)
        self.проверить_полноту(узел, знач.тип)
        ветвление = self.точка("проверка", узел)
        self.держать(знач, ветвление)
        режим_сопоставления = self.режим_сопоставления(знач)
        концы = []
        типы = []
        линейная_нагрузка = знач.место is None and линейный(знач.тип)
        if знач.место is not None and линейный(знач.тип) and not isinstance(знач.тип, Ссылка):
            self.точка("переместить", узел.значение, место=знач.место)
            ветвление = self.текущая
        for ветвь in узел.ветви:
            self.текущая = ветвление
            self.точка("ветвь", ветвь)
            self.войти("ветвь", ветвь)
            привязки = []
            self.собрать_привязки(ветвь.образец, знач.тип, знач, привязки, режим_сопоставления)
            for имя, значение, изм in привязки:
                self.связать_значение(имя, изм, значение, значение.узел)
            if ветвь.охрана is not None:
                self.вычислить(ветвь.охрана, режим="чтение")
            тело = ветвь.тело
            if тело.вид == "блок":
                for инструкция in тело.инструкции:
                    self.инструкция(инструкция)
            elif тело.вид == "выражение":
                значение = self.вычислить(тело.значение, ожидаемый, режим="значение" if режим != "инструкция" else "инструкция")
                if значение is not None and not (isinstance(значение.тип, Простой) and значение.тип.имя == "никогда"):
                    типы.append(значение)
                    if self.текущая is not None:
                        self.держать(значение, self.точка("использовать", тело))
            else:
                self.инструкция(тело)
            if self.текущая is not None:
                self.выйти_из_области(ветвь.последний)
            else:
                self.области.pop()
            концы.append(self.текущая)
        self.слить(концы, узел)
        if not типы:
            return Знач(НИКОГДА if self.текущая is None else ПУСТО, узел, self.номер_текущей())
        тип = None
        for значение in типы:
            if not isinstance(значение.тип, Неизвестный):
                тип = значение.тип
                break
        тип = тип or типы[0].тип
        общий = self.освежить(тип, узел, "выбор")
        for значение in типы:
            self.подтип(значение.тип, общий, значение.узел, "выбор")
        return Знач(общий, узел, self.номер_текущей(), отслеживаемое=any(з.отслеживаемое for з in типы))

    def проверить_полноту(self, узел, тип):
        строки = [[ветвь.образец] for ветвь in узел.ветви if ветвь.охрана is None]
        недостаёт = self.недостающее(строки, [тип], 0)
        if недостаёт is not None:
            self.ошибка(узел, "С0301", f"`выбор` перебирает не все значения: нет ветви для `{недостаёт[0]}`", якорь="выбор")

    @staticmethod
    def снять_ссылки(тип):
        while isinstance(тип, Ссылка):
            тип = тип.цель
        return тип

    def конструкторы(self, тип):
        тип = self.снять_ссылки(тип)
        if isinstance(тип, Опц):
            return [("Есть", [("", тип.внутр)]), ("Ничего", [])]
        if isinstance(тип, Простой) and тип.имя == "бул":
            return [("да", []), ("нет", [])]
        if isinstance(тип, Кортеж):
            return [("()", [("", элемент) for элемент in тип.элементы])]
        if isinstance(тип, Составной):
            объявление = тип.объявление
            if объявление.вид == "переч":
                return [(имя, тип.вариант(имя) or []) for имя in объявление.варианты]
            if объявление.вид == "структ" and объявление.поля:
                return [(объявление.имя, [(имя, тип.поле(имя)) for имя in объявление.поля])]
        return None

    @staticmethod
    def любой(образец):
        if образец is None or образец.вид in ("образец_любой", "образец_изм"):
            return True
        if образец.вид == "образец_имя" and len(образец.путь) == 1 and образец.аргументы is None and образец.поля is None:
            return not образец.путь[0][:1].isupper()
        return False

    @staticmethod
    def имя_образца(образец):
        if образец.вид == "образец_литерал" and образец.до is None and образец.от.вид_лит == "БУЛ":
            return образец.от.значение
        if образец.вид == "образец_кортеж":
            return "()"
        if образец.вид == "образец_имя":
            return образец.путь[-1]
        return None

    @staticmethod
    def части_образца(образец, поля):
        if образец.вид == "образец_кортеж":
            return list(образец.элементы)
        if образец.вид != "образец_имя":
            return [None] * len(поля)
        части = [None] * len(поля)
        имена = [имя for имя, _ in поля]
        if образец.аргументы:
            for номер, (метка, подобразец) in enumerate(образец.аргументы):
                место = имена.index(метка) if метка in имена else номер
                if место < len(части):
                    части[место] = подобразец
        if образец.поля:
            for имя, подобразец, _ in образец.поля:
                if имя in имена:
                    части[имена.index(имя)] = подобразец
        return части

    @staticmethod
    def свидетель(имя, части):
        if имя == "()":
            return "(" + ", ".join(части) + ")"
        return f"{имя}({', '.join(части)})" if части else имя

    def недостающее(self, строки, типы, глубина):
        if not типы:
            return None if строки else []
        if глубина > 12:
            return None
        развёрнутые = []
        for строка in строки:
            голова = строка[0]
            if голова is not None and голова.вид == "образец_или":
                развёрнутые += [[альтернатива] + строка[1:] for альтернатива in голова.альтернативы]
            else:
                развёрнутые.append(строка)
        строки = развёрнутые
        конструкторы = self.конструкторы(типы[0])
        if конструкторы is None or all(self.любой(строка[0]) for строка in строки):
            остаток = [строка[1:] for строка in строки if self.любой(строка[0])]
            if not остаток:
                return ["_"] * len(типы)
            хвост = self.недостающее(остаток, типы[1:], глубина + 1)
            return None if хвост is None else ["_"] + хвост
        for имя, поля in конструкторы:
            частные = []
            for строка in строки:
                голова = строка[0]
                if self.любой(голова):
                    частные.append([None] * len(поля) + строка[1:])
                elif self.имя_образца(голова) == имя:
                    частные.append(self.части_образца(голова, поля) + строка[1:])
            if not частные:
                return [self.свидетель(имя, ["_"] * len(поля))] + ["_"] * (len(типы) - 1)
            найдено = self.недостающее(частные, [тип_поля for _, тип_поля in поля] + типы[1:], глубина + 1)
            if найдено is not None:
                return [self.свидетель(имя, найдено[:len(поля)])] + найдено[len(поля):]
        return None

    def вместе(self, узел, ожидаемый):
        ветви = []
        все_заёмы = []
        for аргумент in узел.аргументы:
            до = len(self.заёмы)
            self.ветвь_вместе = True
            знач = self.вычислить(аргумент)
            self.ветвь_вместе = False
            ветви.append(знач)
            все_заёмы.append(self.заёмы[до:])
        точка = self.точка("вместе", узел)
        for знач in ветви:
            self.держать(знач, точка)
        self.проверить_одновременность(все_заёмы, "ветви")
        if узел.форма == "первый":
            тип = None
            for знач in ветви:
                if isinstance(знач.тип, Функция) and знач.тип.результат is not None:
                    кандидат = знач.тип.результат
                    if isinstance(кандидат, Составной) and кандидат.типы and isinstance(кандидат.типы[0], Простой) and кандидат.типы[0].имя == "никогда":
                        continue
                    тип = кандидат
                    break
            if тип is None and ветви and isinstance(ветви[0].тип, Функция):
                тип = ветви[0].тип.результат
            return Знач(тип or Неизвестный("первый"), узел, точка.номер)
        итоги = []
        ошибка = None
        for знач in ветви:
            тип = знач.тип
            if isinstance(тип, Составной) and тип.объявление.имя == "Итог":
                итоги.append(тип.типы[0])
                ошибка = тип.типы[1]
            else:
                итоги.append(тип)
        значимые = [т for т in итоги if not (isinstance(т, Простой) and т.имя == "пусто")]
        успех = ПУСТО if not значимые else значимые[0] if len(значимые) == 1 else Кортеж(значимые)
        if ошибка is not None:
            return Знач(Составной(self.п.прелюдия.типы["Итог"], [успех, ошибка], []), узел, точка.номер)
        return Знач(успех, узел, точка.номер)

    def проверить_одновременность(self, группы, вид):
        for номер, группа in enumerate(группы):
            for другой in range(номер):
                for заём in группа:
                    for ранний in группы[другой]:
                        if заём.место.корень is ранний.место.корень and self.пересекаются(заём.место, ранний.место) and (заём.изм or ранний.изм):
                            сообщение = (
                                f"`{заём.место.корень.имя}` заимствован исключительно дважды, а ветви `вместе` выполняются одновременно"
                                if вид == "ветви" else
                                f"`{заём.место.корень.имя}` заимствован исключительно, а аргументы одного вызова заимствуют одновременно"
                            )
                            подсказка = "первое исключительное заимствование" if ранний.изм else "первое заимствование"
                            if вид == "ветви" and isinstance(заём.место.тип, Массив):
                                подсказка += f"; непересекающиеся части даёт `{self.текст(ранний.узел)}.разделить(середина)`"
                            self.ошибка(заём.узел, "С0407", сообщение, [(ранний.узел, подсказка)])

    def пересекаются(self, а, б):
        путь_а = [шаг for шаг in а.путь]
        путь_б = [шаг for шаг in б.путь]
        for шаг_а, шаг_б in zip(путь_а, путь_б):
            if шаг_а[0] != шаг_б[0]:
                return False
            if шаг_а[0] == "поле" and шаг_а[1] != шаг_б[1]:
                return False
        return True

