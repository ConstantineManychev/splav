def переносимый(тип, глубина=0):
    if глубина > 8 or not линейный(тип) or isinstance(тип, РегЗначение):
        return True
    if isinstance(тип, Составной):
        объявление = тип.объявление
        if объявление.имя == "Общий" and объявление.модуль.имя == "ядро.память":
            return True
        if объявление.линейный_явно:
            return False
        части = [тип.поле(имя) for имя in объявление.поля]
        части += [поле for имя in объявление.варианты for _, поле in (тип.вариант(имя) or [])]
        return all(переносимый(часть, глубина + 1) for часть in части if часть is not None)
    if isinstance(тип, Кортеж):
        return all(переносимый(элемент, глубина + 1) for элемент in тип.элементы)
    if isinstance(тип, Опц):
        return переносимый(тип.внутр, глубина + 1)
    return False


