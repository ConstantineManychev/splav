import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from вставка import ИСТОЧНИКИ
from мутанты import главная as мутанты
from проверить import проверить_пакет

КОРПУС = pathlib.Path(__file__).resolve().parent.parent / "корпус"
ПАКЕТЫ = ["json", "эхо", "частицы", "ecs", "сжать"]


def главная():
    успех = True
    for пакет in ПАКЕТЫ:
        результаты, библиотека, неподдержано = проверить_пакет(КОРПУС / пакет)
        строки = [строка for строки in результаты.values() for строка in строки] + библиотека
        чисто = not строки and not неподдержано
        успех &= чисто
        print(f"{'✓' if чисто else '✗'} {пакет}: {len(результаты)} файлов, диагностик {len(строки)}, неподдержано {len(неподдержано)}")
        for строка in строки:
            print(f"    {строка}")
        for модуль, номер, что in неподдержано:
            print(f"    неподдержано {модуль.имя}:{номер}: {что}")
    for заголовок, источник in sorted(ИСТОЧНИКИ.items()):
        print(f"  вставка \"{заголовок}\": {источник}")
    print("мутанты корпуса:")
    успех &= мутанты()
    return успех


if __name__ == "__main__":
    sys.exit(0 if главная() else 1)
