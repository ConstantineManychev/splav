import itertools

_номера = itertools.count(1)


class Регион:
    def __init__(self, вид, имя, узел=None, **данные):
        self.вид = вид
        self.имя = имя
        self.узел = узел
        self.номер = next(_номера)
        self.__dict__.update(данные)

    def конкретный(self):
        return self.вид != "переменная"

    def __repr__(self):
        return f"{self.вид}:{self.имя}#{self.номер}"


СТАТИЧ = Регион("статич", "статич")
ЗАДАЧА = Регион("задача", "задача")


def переменная(происхождение, узел=None):
    return Регион("переменная", происхождение, узел)


