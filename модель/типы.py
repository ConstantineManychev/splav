class Ссылка(Тип):
    def __init__(self, изм, регион, цель):
        self.изм = изм
        self.регион = регион
        self.цель = цель

    def __repr__(self):
        return f"&{self.регион!r}{' изм' if self.изм else ''} {self.цель!r}"

    def собрать(self, итог, вариантность):
        итог.append((self.регион, вариантность))
        self.цель.собрать(итог, "ин" if self.изм else вариантность)

    def заменить(self, регионы, типы=None):
        return Ссылка(self.изм, регионы.get(self.регион, self.регион), self.цель.заменить(регионы, типы))


class Срез(Тип):
    def __init__(self, изм, регион, элемент, строка=False):
        self.изм = изм
        self.регион = регион
        self.элемент = элемент
        self.строка = строка

    def __repr__(self):
        if self.строка:
            return f"стр{self.регион!r}"
        return f"[]{self.регион!r}{' изм' if self.изм else ''} {self.элемент!r}"

    def собрать(self, итог, вариантность):
        итог.append((self.регион, вариантность))
        self.элемент.собрать(итог, "ин" if self.изм else вариантность)

    def заменить(self, регионы, типы=None):
        return Срез(self.изм, регионы.get(self.регион, self.регион), self.элемент.заменить(регионы, типы), self.строка)


