class Кортеж(Тип):
    def __init__(self, элементы):
        self.элементы = элементы

    def __repr__(self):
        return "(" + ", ".join(map(repr, self.элементы)) + ")"

    def собрать(self, итог, вариантность):
        for элемент in self.элементы:
            элемент.собрать(итог, вариантность)

    def заменить(self, регионы, типы=None):
        return Кортеж([элемент.заменить(регионы, типы) for элемент in self.элементы])


class Составной(Тип):
    def __init__(self, объявление, типы, регионы):
        self.объявление = объявление
        self.типы = типы
        self.регионы_объекта = регионы

    def __repr__(self):
        части = [repr(тип) for тип in self.типы]
        регионы = "".join(f"<{регион!r}>" for регион in self.регионы_объекта)
        return f"{self.объявление.имя}{'(' + ', '.join(части) + ')' if части else ''}{регионы}"

    def собрать(self, итог, вариантность):
        for номер, регион in enumerate(self.регионы_объекта):
            if номер == 0 and капсула(self.объявление):
                continue
            итог.append((регион, "ин" if self.объявление.инвариантен_регион(номер) else вариантность))
        for номер, тип in enumerate(self.типы):
            тип.собрать(итог, "ин" if self.объявление.инвариантен_тип(номер) else вариантность)

    def заменить(self, регионы, типы=None):
        return Составной(
            self.объявление,
            [тип.заменить(регионы, типы) for тип in self.типы],
            [регионы.get(регион, регион) for регион in self.регионы_объекта],
        )

    def подстановка_типов(self):
        return {имя: тип for имя, тип in zip(self.объявление.параметры_типов, self.типы)}

    def подстановка_регионов(self):
        return dict(zip(self.объявление.параметры_регионов, self.регионы_объекта))

    def поле(self, имя):
        шаблон = self.объявление.поля.get(имя)
        if шаблон is None:
            return None
        return шаблон.заменить(self.подстановка_регионов(), self.подстановка_типов())

    def вариант(self, имя):
        шаблон = self.объявление.варианты.get(имя)
        if шаблон is None:
            return None
        return [(метка, тип.заменить(self.подстановка_регионов(), self.подстановка_типов())) for метка, тип in шаблон]


