class Функция(Тип):
    def __init__(self, вид, параметры, результат, регионы=()):
        self.вид = вид
        self.параметры = параметры
        self.результат = результат
        self.захваченные = list(регионы)

    def __repr__(self):
        return f"функ[{self.вид}]({', '.join(map(repr, self.параметры))}) -> {self.результат!r}"

    def собрать(self, итог, вариантность):
        for регион in self.захваченные:
            итог.append((регион, вариантность))
        for параметр in self.параметры:
            параметр.собрать(итог, "ин")
        if self.результат is not None:
            self.результат.собрать(итог, вариантность)

    def заменить(self, регионы, типы=None):
        return Функция(
            self.вид,
            [параметр.заменить(регионы, типы) for параметр in self.параметры],
            self.результат.заменить(регионы, типы) if self.результат is not None else None,
            [регионы.get(регион, регион) for регион in self.захваченные],
        )


