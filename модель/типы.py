class Простой(Тип):
    def __init__(self, имя):
        self.имя = имя

    def __repr__(self):
        return self.имя

    def __eq__(self, другой):
        return isinstance(другой, Простой) and другой.имя == self.имя

    def __hash__(self):
        return hash(self.имя)


