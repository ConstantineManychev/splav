class Программа:
    def __init__(self, корень_пакета):
        self.корень = pathlib.Path(корень_пакета) if корень_пакета else None
        self.модули = {}
        self.ошибки_объявлений = []
        self.вставки = {}
        self.объявления_си = {}
        self.прелюдия = None
        self.прелюдия = self.загрузить("ядро.прелюдия")
        self.прелюдия_имена = self.прелюдия.типы

    def путь_модуля(self, имя):
        части = имя.split(".")
        if self.корень is not None:
            кандидат = self.корень.joinpath(*части).with_suffix(".спл")
            if кандидат.exists():
                return кандидат
        кандидат = БИБЛИОТЕКА.joinpath(*части).with_suffix(".спл")
        if кандидат.exists():
            return кандидат
        raise ОшибкаПрограммы(f"нет модуля {имя}")

    def загрузить(self, имя, путь=None, исходник=None):
        if имя in self.модули:
            return self.модули[имя]
        if исходник is None:
            путь = путь or self.путь_модуля(имя)
            исходник = путь.read_text(encoding="utf-8")
        дерево = разобрать(исходник, "модуль")
        модуль = Модуль(имя, путь, исходник, дерево, self)
        self.модули[имя] = модуль
        self.собрать_объявления(модуль)
        for элемент in дерево.элементы:
            if элемент.вид == "подключить":
                цель = self.загрузить(".".join(элемент.путь))
                модуль.подключения[элемент.псевдоним or элемент.путь[-1]] = цель
            elif элемент.вид == "вставка":
                заголовок = элемент.файл.strip('"')
                цель = self.загрузить_заголовок(заголовок)
                модуль.подключения[элемент.псевдоним or pathlib.PurePosixPath(заголовок).stem] = цель
                self.закрепить(цель, элемент)
        return модуль

    def загрузить_заголовок(self, заголовок):
        ключ = f"вставка {заголовок}"
        if ключ in self.модули:
            return self.модули[ключ]
        try:
            образ = вставка.образ(заголовок)
        except вставка.ОшибкаВставки as ошибка:
            raise ОшибкаПрограммы(str(ошибка))
        self.вставки[заголовок] = образ
        модуль = self.загрузить(ключ, исходник=образ.текст)
        модуль.путь = pathlib.Path(f"<{заголовок}>")
        for имя, место in образ.ключи.items():
            if имя not in модуль.типы:
                continue
            прежнее = self.объявления_си.setdefault(место, модуль.типы[имя])
            модуль.типы[имя] = прежнее
        return модуль

    def закрепить(self, модуль, элемент):
        for атрибут in элемент.атрибуты:
            if атрибут.имя != "Закреплённый":
                continue
            for _, значение in атрибут.аргументы or []:
                имя = getattr(значение, "имя", None)
                объявление = модуль.типы.get(имя)
                if объявление is None:
                    raise ОшибкаПрограммы(f"{атрибут.строка}:{атрибут.столбец}: в {элемент.файл} нет типа {имя}")
                объявление.закреплённый_явно = True

    def собрать_объявления(self, модуль):
        for элемент in модуль.дерево.элементы:
            атрибуты = {атрибут.имя for атрибут in элемент.атрибуты}
            if элемент.вид in ("структ", "набор", "переч"):
                объявление = ОбъявлениеТипа(элемент.имя, элемент.вид, модуль, элемент)
                объявление.линейный_явно = "Линейный" in атрибуты
                объявление.закреплённый_явно = "Закреплённый" in атрибуты
                объявление.встроено = "Встроено" in атрибуты
                объявление.параметры_типов = [параметр.имя for параметр in элемент.параметры]
                модуль.типы[элемент.имя] = объявление
            elif элемент.вид == "функция":
                функция = ОбъявлениеФункции(элемент.сигнатура.имя, модуль, элемент)
                модуль.функции_список.append(функция)
                if элемент.сигнатура.владелец is not None:
                    модуль.методы.setdefault(элемент.сигнатура.владелец, {})[функция.имя] = функция
                else:
                    модуль.функции[функция.имя] = функция
            elif элемент.вид == "конст":
                модуль.константы[элемент.имя] = Константа(элемент.имя, модуль, элемент)
            elif элемент.вид == "типаж":
                модуль.типажи[элемент.имя] = элемент
            elif элемент.вид == "реализ":
                модуль.функции_список.extend([])

    def подготовить(self):
        for модуль in list(self.модули.values()):
            for объявление in модуль.типы.values():
                объявление.методы = модуль.методы.get(объявление.имя, {})
        объявления = list({id(объявление): объявление for модуль in self.модули.values()
                           for объявление in модуль.типы.values()}.values())
        for объявление in объявления:
            объявление.капсула = self.поле_региона(объявление) is not None
            for узел_типа in self.узлы_полей(объявление):
                self.собрать_метки(узел_типа, объявление.имена_меток)
        имеет = {объявление: False for объявление in объявления}
        изменилось = True
        while изменилось:
            изменилось = False
            for объявление in объявления:
                if имеет[объявление]:
                    continue
                if self.поля_содержат_регионы(объявление, имеет):
                    имеет[объявление] = True
                    изменилось = True
        for объявление in объявления:
            метки = объявление.имена_меток
            регионы = []
            if имеет[объявление] or метки:
                регионы.append(Регион("параметр", "объект"))
            for метка in sorted(метки):
                регион = Регион("параметр", метка)
                объявление.метки[метка] = регион
                регионы.append(регион)
            объявление.параметры_регионов = регионы
        for объявление in объявления:
            self.разрешить_поля(объявление)
        self.вычислить_вариантность(объявления)

    def поле_региона(self, объявление):
        if объявление.вид == "переч" or объявление.узел is None or not hasattr(объявление.узел, "поля"):
            return None
        for поле in объявление.узел.поля or []:
            узел = поле.тип
            цель = None
            if узел.вид == "имя":
                цель = self.найти_тип_по_имени(объявление.модуль, узел.имя)
            elif узел.вид == "поле":
                цель = self.найти_тип_по_пути(объявление.модуль, узел)
            if isinstance(цель, ОбъявлениеТипа) and цель.имя == "Рег" and цель.модуль.имя == "ядро.память":
                return поле
        return None

    def узлы_полей(self, объявление):
        if объявление.вид == "переч":
            for вариант in объявление.узел.варианты:
                for _, узел_типа in вариант.поля or []:
                    yield узел_типа
        else:
            for поле in объявление.узел.поля:
                yield поле.тип

    def собрать_метки(self, узел, метки):
        if узел is None or not isinstance(узел, Узел):
            return
        if узел.вид == "ссылка" and узел.метка:
            метки.add(узел.метка)
        for значение in vars(узел).values():
            if isinstance(значение, Узел) and значение is not узел.первый:
                self.собрать_метки(значение, метки)
            elif isinstance(значение, list):
                for элемент in значение:
                    if isinstance(элемент, Узел):
                        self.собрать_метки(элемент, метки)
                    elif isinstance(элемент, tuple):
                        for часть in элемент:
                            if isinstance(часть, Узел):
                                self.собрать_метки(часть, метки)

    def поля_содержат_регионы(self, объявление, имеет):
        for узел_типа in self.узлы_полей(объявление):
            if self.узел_содержит_регионы(узел_типа, объявление.модуль, имеет, set(объявление.параметры_типов)):
                return True
        return False

    def узел_содержит_регионы(self, узел, модуль, имеет, параметры):
        if узел is None:
            return False
        вид = узел.вид
        if вид in ("ссылка", "тип_срез", "тип_терм_срез"):
            return True
        if вид == "имя":
            if узел.имя == "стр":
                return True
            if узел.имя in параметры or узел.имя in ПРОСТЫЕ:
                return False
            объявление = self.найти_тип_по_имени(модуль, узел.имя)
            if isinstance(объявление, ОбъявлениеТипа):
                return bool(объявление.имена_меток) if объявление.капсула else имеет.get(объявление, False)
            return False
        if вид == "поле":
            объявление = self.найти_тип_по_пути(модуль, узел)
            if isinstance(объявление, ОбъявлениеТипа):
                return bool(объявление.имена_меток) if объявление.капсула else имеет.get(объявление, False)
            return False
        if вид == "вызов":
            if self.узел_содержит_регионы(узел.функция, модуль, имеет, параметры):
                return True
            return any(self.узел_содержит_регионы(аргумент, модуль, имеет, параметры) for аргумент in узел.аргументы)
        if вид in ("опц", "тип_массив", "скобки", "дин"):
            return self.узел_содержит_регионы(getattr(узел, "операнд", None) or getattr(узел, "значение", None), модуль, имеет, параметры)
        if вид == "кортеж":
            return any(self.узел_содержит_регионы(элемент, модуль, имеет, параметры) for элемент in узел.элементы)
        return False

    def найти_тип_по_имени(self, модуль, имя):
        if имя in модуль.типы:
            return модуль.типы[имя]
        if self.прелюдия is not None and имя in self.прелюдия.типы:
            return self.прелюдия.типы[имя]
        if имя in модуль.константы:
            псевдоним = self.константа_как_тип(модуль.константы[имя])
            if isinstance(псевдоним, Составной):
                return псевдоним.объявление
        return None

    def найти_тип_по_пути(self, модуль, узел):
        if узел.вид == "поле" and узел.объект.вид == "имя" and узел.объект.имя in модуль.подключения:
            цель = модуль.подключения[узел.объект.имя]
            return self.найти_тип_по_имени(цель, узел.имя)
        return None

    def разрешить_поля(self, объявление):
        параметры = {имя: ПараметрТипа(имя) for имя in объявление.параметры_типов}
        область = ОбластьТипов(объявление.модуль, параметры)
        объект = объявление.параметры_регионов[0] if объявление.параметры_регионов else None

        def регион_поля(роль, метка, узел):
            if метка is not None and метка in объявление.метки:
                return объявление.метки[метка]
            return объект if объект is not None else СТАТИЧ

        if объявление.вид == "переч":
            for вариант in объявление.узел.варианты:
                объявление.варианты[вариант.имя] = [
                    (метка, self.разрешить_тип(узел_типа, область, регион_поля, поле=True))
                    for метка, узел_типа in (вариант.поля or [])
                ]
        else:
            регионы = []
            for поле in объявление.узел.поля:
                объявление.поля[поле.имя] = self.разрешить_тип(поле.тип, область, регион_поля, поле=True)
                if поле.откр:
                    объявление.откр_поля.add(поле.имя)
                if isinstance(объявление.поля[поле.имя], РегЗначение):
                    регионы.append(поле)
            объявление.поле_рег = регионы[0].имя if регионы else None
            for лишнее in регионы[1:]:
                self.ошибки_объявлений.append((
                    объявление.модуль, лишнее, "С0417",
                    f"в капсуле `{объявление.имя}` второе поле `Рег`: регион капсулы задаёт ровно одно",
                    [(регионы[0], f"регион капсулы — поле `{регионы[0].имя}`")], лишнее.имя,
                ))

    def вычислить_вариантность(self, объявления):
        изменилось = True
        while изменилось:
            изменилось = False
            for объявление in объявления:
                шаблоны = list(объявление.поля.values()) + [
                    тип for поля in объявление.варианты.values() for _, тип in поля
                ]
                for шаблон in шаблоны:
                    for регион, вариантность in self.обход_вариантности(шаблон, "ко"):
                        if isinstance(регион, Регион) and регион in объявление.параметры_регионов and вариантность == "ин":
                            номер = объявление.параметры_регионов.index(регион)
                            if номер not in объявление.инвариантные_регионы:
                                объявление.инвариантные_регионы.add(номер)
                                изменилось = True
                        if isinstance(регион, ПараметрТипа) and вариантность == "ин" and регион.имя in объявление.параметры_типов:
                            номер = объявление.параметры_типов.index(регион.имя)
                            if номер not in объявление.инвариантные_типы:
                                объявление.инвариантные_типы.add(номер)
                                изменилось = True

    def обход_вариантности(self, тип, вариантность):
        if isinstance(тип, ПараметрТипа):
            yield тип, вариантность
        elif isinstance(тип, Ссылка):
            yield тип.регион, вариантность
            yield from self.обход_вариантности(тип.цель, "ин" if тип.изм else вариантность)
        elif isinstance(тип, Срез):
            yield тип.регион, вариантность
            yield from self.обход_вариантности(тип.элемент, "ин" if тип.изм else вариантность)
        elif isinstance(тип, Арена):
            yield тип.регион, "ин"
        elif isinstance(тип, (Опц,)):
            yield from self.обход_вариантности(тип.внутр, вариантность)
        elif isinstance(тип, Массив):
            yield from self.обход_вариантности(тип.элемент, вариантность)
        elif isinstance(тип, Кортеж):
            for элемент in тип.элементы:
                yield from self.обход_вариантности(элемент, вариантность)
        elif isinstance(тип, Составной):
            for номер, регион in enumerate(тип.регионы_объекта):
                yield регион, "ин" if тип.объявление.инвариантен_регион(номер) else вариантность
            for номер, аргумент in enumerate(тип.типы):
                yield from self.обход_вариантности(аргумент, "ин" if тип.объявление.инвариантен_тип(номер) else вариантность)
        elif isinstance(тип, Функция):
            for регион in тип.захваченные:
                yield регион, вариантность

    def константа_как_тип(self, константа):
        if константа.псевдоним is not None or константа.в_работе:
            return константа.псевдоним
        узел = константа.узел.значение
        if константа.узел.тип is None and self.похоже_на_тип(узел, константа.модуль):
            константа.в_работе = True
            try:
                константа.псевдоним = self.разрешить_тип(узел, ОбластьТипов(константа.модуль), lambda р, м, у: СТАТИЧ)
            except ОшибкаПрограммы:
                константа.псевдоним = None
            константа.в_работе = False
        return константа.псевдоним

    def похоже_на_тип(self, узел, модуль):
        if узел.вид == "вызов":
            return self.похоже_на_тип(узел.функция, модуль)
        if узел.вид == "имя":
            if узел.имя in ("Вектор",) or узел.имя in ПРОСТЫЕ:
                return True
            if self.найти_тип_по_имени(модуль, узел.имя) is not None:
                return True
            константа = модуль.константы.get(узел.имя)
            return константа is not None and self.константа_как_тип(константа) is not None
        if узел.вид == "поле":
            return self.найти_тип_по_пути(модуль, узел) is not None
        return узел.вид in ("опц", "сырой", "тип_терм_указатель", "тип_массив", "тип_срез", "тип_терм_срез", "тип_функции")

    def разрешить_тип(self, узел, область, регион_для, поле=False, роль="внешний"):
        вид = узел.вид
        if вид == "скобки":
            return self.разрешить_тип(узел.значение, область, регион_для, поле, роль)
        if вид == "имя":
            return self.тип_по_имени(узел, область, [], регион_для, поле)
        if вид == "поле":
            return self.тип_по_полю(узел, область, [], регион_для, поле)
        if вид == "вызов":
            аргументы = узел.аргументы
            if узел.функция.вид == "имя":
                return self.тип_по_имени(узел.функция, область, аргументы, регион_для, поле)
            if узел.функция.вид == "поле":
                return self.тип_по_полю(узел.функция, область, аргументы, регион_для, поле)
            raise ОшибкаПрограммы(f"{узел.строка}:{узел.столбец}: не тип")
        if вид == "ссылка":
            операнд = узел.операнд
            if операнд.вид == "тип_функции":
                функция = self.разрешить_тип(операнд, область, регион_для, поле, "внутренний")
                функция.вид = "изм" if узел.изм else "замыкание"
                функция.захваченные = [регион_для(роль, узел.метка, узел)]
                return функция
            if операнд.вид == "имя" and операнд.имя == "Регион":
                return Арена(регион_для(роль, узел.метка, узел))
            if операнд.вид == "дин":
                return Ссылка(узел.изм, регион_для(роль, узел.метка, узел), Неизвестный("дин"))
            регион = регион_для(роль, узел.метка, узел)
            цель = self.разрешить_тип(операнд, область, регион_для, поле, "внутренний")
            return Ссылка(узел.изм, регион, цель)
        if вид == "опц":
            return Опц(self.разрешить_тип(узел.операнд, область, регион_для, поле, роль))
        if вид in ("тип_срез", "тип_терм_срез"):
            регион = регион_для(роль, None, узел)
            элемент = self.разрешить_тип(узел.операнд, область, регион_для, поле, "внутренний")
            return Срез(узел.изм, регион, элемент)
        if вид == "тип_массив":
            return Массив(self.разрешить_тип(узел.операнд, область, регион_для, поле, роль), узел.длина)
        if вид in ("сырой", "тип_терм_указатель"):
            return Простой("указатель")
        if вид == "дин":
            return Неизвестный("дин")
        if вид == "тип_функции":
            параметры = [
                self.разрешить_тип(параметр.тип, область, регион_для, поле, "внутренний")
                for параметр in узел.параметры if параметр.тип is not None
            ]
            результат = self.разрешить_тип(узел.результат, область, регион_для, поле, "внутренний") if узел.результат else ПУСТО
            return Функция("указатель", параметры, результат)
        if вид == "кортеж":
            return Кортеж([self.разрешить_тип(элемент, область, регион_для, поле, роль) for элемент in узел.элементы])
        if вид == "лит":
            return Простой("число")
        raise ОшибкаПрограммы(f"{узел.строка}:{узел.столбец}: не тип ({вид})")

    def тип_по_имени(self, узел, область, аргументы, регион_для, поле):
        имя = узел.имя
        if имя in область.параметры:
            return область.параметры[имя]
        if имя == "Сам" and область.сам is not None:
            return область.сам
        if имя == "стр":
            return Срез(False, регион_для("внешний", None, узел), Н8, строка=True)
        if имя in ПРОСТЫЕ:
            return Простой(имя)
        if имя == "Вектор":
            элемент = "в32"
            if аргументы and аргументы[0].вид == "имя":
                элемент = аргументы[0].имя
            return Простой(f"вектор/{элемент}")
        объявление = область.модуль.типы.get(имя) or self.прелюдия.типы.get(имя)
        if объявление is not None:
            return self.экземпляр(объявление, аргументы, область, регион_для, поле)
        if имя in область.модуль.константы:
            псевдоним = self.константа_как_тип(область.модуль.константы[имя])
            if псевдоним is not None:
                return self.освежить_псевдоним(псевдоним, регион_для, узел)
        if имя in область.модуль.подключения:
            raise ОшибкаПрограммы(f"{узел.строка}:{узел.столбец}: модуль вместо типа")
        raise ОшибкаПрограммы(f"{узел.строка}:{узел.столбец}: неизвестный тип {имя}")

    def освежить_псевдоним(self, тип, регион_для, узел):
        замены = {}
        for регион in тип.регионы():
            if регион not in замены:
                замены[регион] = регион_для("внутренний", None, узел)
        return тип.заменить(замены)

    def тип_по_полю(self, узел, область, аргументы, регион_для, поле):
        if узел.объект.вид == "имя" and узел.объект.имя in область.модуль.подключения:
            цель = область.модуль.подключения[узел.объект.имя]
            объявление = цель.типы.get(узел.имя)
            if объявление is not None:
                return self.экземпляр(объявление, аргументы, ОбластьТипов(цель), регион_для, поле, область)
            if узел.имя in цель.константы:
                псевдоним = self.константа_как_тип(цель.константы[узел.имя])
                if псевдоним is not None:
                    return self.освежить_псевдоним(псевдоним, регион_для, узел)
        raise ОшибкаПрограммы(f"{узел.строка}:{узел.столбец}: неизвестный тип")

    def экземпляр(self, объявление, аргументы, область, регион_для, поле, область_аргументов=None):
        область_аргументов = область_аргументов or область
        if объявление.встроено and объявление.имя == "Рег":
            return РегЗначение(регион_для("внутренний", None, объявление.узел))
        типы = []
        for аргумент in аргументы:
            if аргумент.вид == "лит":
                типы.append(Простой("число"))
            else:
                типы.append(self.разрешить_тип(аргумент, область_аргументов, регион_для, поле, "внутренний"))
        while len(типы) < len(объявление.параметры_типов):
            типы.append(Неизвестный("тип"))
        регионы = [регион_для("внутренний", None, объявление.узел) for _ in объявление.параметры_регионов]
        if объявление.капсула and регионы:
            основа = регионы[0]
            регионы[0] = Регион("капсула", getattr(основа, "параметр", None) or объявление.имя, объявление.узел, концы=None)
        if объявление.имя == "Рег" and объявление.модуль.имя == "ядро.память":
            return РегЗначение(регионы[0] if регионы else регион_для("внутренний", None, объявление.узел))
        return Составной(объявление, типы, регионы)

    def заголовок(self, функция):
        if функция.заголовок_готов:
            return
        функция.заголовок_готов = True
        модуль = функция.модуль
        сигнатура = функция.сигнатура
        параметры = {}
        владелец = None
        if сигнатура.владелец is not None:
            владелец = модуль.типы.get(сигнатура.владелец) or self.прелюдия.типы.get(сигнатура.владелец)
            if владелец is None:
                if сигнатура.владелец in ПРОСТЫЕ or сигнатура.владелец == "стр":
                    владелец = сигнатура.владелец
                else:
                    raise ОшибкаПрограммы(f"неизвестный владелец {сигнатура.владелец}")
            функция.владелец = владелец
            for номер, параметр in enumerate(сигнатура.параметры_владельца):
                параметры[параметр.имя] = ПараметрТипа(параметр.имя)
                функция.параметры_владельца.append(параметр.имя)
        for параметр in сигнатура.параметры:
            if параметр.компил:
                параметры[параметр.имя] = ПараметрТипа(параметр.имя)
                функция.компил.append(параметр.имя)
        функция.требует = сигнатура.требует is not None
        контекст = Регион("сигнатура", "контекст", сигнатура, роль="контекст") if функция.требует else None
        функция.контекст = контекст
        сам_тип = None
        if isinstance(владелец, ОбъявлениеТипа):
            сам_тип = Составной(
                владелец,
                [параметры.get(имя, ПараметрТипа(имя)) for имя in (функция.параметры_владельца or владелец.параметры_типов)],
                [],
            )
        область = ОбластьТипов(модуль, параметры, сам_тип)
        регионы = функция.регионы_сигнатуры

        def новый(роль, метка, узел, параметр):
            регион = Регион("сигнатура", метка or роль, узел, роль=роль, параметр=параметр, метка=метка)
            регионы.append(регион)
            return регион

        метки = {}

        def фабрика(имя_параметра):
            def регион_для(роль, метка, узел):
                if метка is not None:
                    if метка not in метки:
                        метки[метка] = новый("метка", метка, узел, имя_параметра)
                    return метки[метка]
                return новый(роль, None, узел, имя_параметра)
            return регион_для

        for параметр in сигнатура.параметры:
            if параметр.компил:
                функция.параметры.append(Параметр(параметр.имя, "компил", ТИП, True, False, параметр))
                continue
            if параметр.форма in ("сам", "&сам", "&изм сам"):
                if сам_тип is None:
                    if isinstance(владелец, str):
                        базовый = Срез(False, новый("внешний", None, параметр, "сам"), Н8, строка=True) if владелец == "стр" else Простой(владелец)
                        функция.параметры.append(Параметр("сам", параметр.форма, базовый, False, False, параметр))
                        continue
                    raise ОшибкаПрограммы("сам вне метода")
                фабрика_сам = фабрика("сам")
                if владелец.имя == "Рег" and владелец.модуль.имя == "ядро.память":
                    функция.параметры.append(Параметр("сам", параметр.форма, РегЗначение(фабрика_сам("внутренний", None, параметр)), False, False, параметр))
                    continue
                внутренний_сам = Составной(
                    владелец,
                    list(сам_тип.типы),
                    [фабрика_сам("внутренний", None, параметр) for _ in владелец.параметры_регионов],
                )
                if параметр.форма == "сам":
                    тип = внутренний_сам
                else:
                    тип = Ссылка(параметр.форма == "&изм сам", фабрика_сам("внешний", None, параметр), внутренний_сам)
                функция.параметры.append(Параметр("сам", параметр.форма, тип, False, False, параметр))
                continue
            if параметр.форма == "пакет":
                функция.параметры.append(Параметр(параметр.имя, "пакет", Неизвестный("пакет"), False, False, параметр))
                continue
            тип = self.разрешить_тип(параметр.тип, область, фабрика(параметр.имя))
            функция.параметры.append(Параметр(параметр.имя, параметр.форма, тип, False, параметр.изм, параметр))
        if сигнатура.результат is not None:
            функция.результат = self.разрешить_тип(сигнатура.результат, область, фабрика(None), роль="результат")
            for регион in регионы:
                if регион.параметр is None and регион.роль in ("внешний", "внутренний"):
                    регион.роль = "результат"
        if функция.встроено:
            функция.контракт = self.контракт_по_умолчанию(функция)

    def контракт_по_умолчанию(self, функция):
        внешние = [р for р in функция.регионы_сигнатуры if р.роль == "внешний"]
        внутренние = [р for р in функция.регионы_сигнатуры if р.роль == "внутренний"]
        результат = [р for р in функция.регионы_сигнатуры if р.роль == "результат"]
        итог = []
        if функция.контекст is not None:
            for регион in внутренние + результат:
                итог.append((функция.контекст, регион, None))
                итог.append((регион, функция.контекст, None))
            return итог
        if внутренние:
            главный = внутренние[0]
            for регион in внутренние[1:] + результат:
                итог.append((главный, регион, None))
                итог.append((регион, главный, None))
            return итог
        for регион in результат:
            for внешний in внешние:
                итог.append((внешний, регион, None))
            if not внешние:
                итог.append((СТАТИЧ, регион, None))
                итог.append((регион, СТАТИЧ, None))
        return итог

    def методы_типа(self, тип):
        if isinstance(тип, Составной):
            return тип.объявление.методы
        if isinstance(тип, Срез) and тип.строка:
            return self.прелюдия.методы.get("стр", {})
        if isinstance(тип, Простой):
            return self.прелюдия.методы.get(тип.имя, {})
        if isinstance(тип, РегЗначение):
            память = self.модули.get("ядро.память")
            return память.методы.get("Рег", {}) if память else {}
        return {}
