import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "грамматика"))

from прототип import Узел
from анализ import Решатель
from программа import Программа
from тело import Анализ

СЛУЖЕБНЫЕ = {"пакет.спл", "сборка.спл"}


class Отчёт:
    def __init__(self):
        self.записи = []
        self.анализы = []

    def добавить(self, модуль, узел, код, сообщение, примечания, якорь=None):
        self.записи.append((модуль, узел, код, сообщение, примечания, якорь))


def место_узла(узел, исходник, якорь=None):
    if isinstance(узел, Узел):
        текст = якорь or узел.текст(исходник)
        return узел.строка, узел.столбец, текст.split("\n")[0]
    return узел.строка, узел.столбец, якорь or узел.текст


def строки_отчёта(отчёт, модуль):
    итог = []
    виденные = set()
    for модуль_записи, узел, код, сообщение, примечания, якорь in отчёт.записи:
        if модуль_записи is not модуль:
            continue
        якорь = якорь or (getattr(узел, "якорь", None) if not isinstance(узел, Узел) else None)
        if isinstance(узел, Узел) and узел.вид == "префикс" and узел.оп == "попытка":
            якорь = "попытка"
        строка, столбец, текст = место_узла(узел, модуль.исходник, якорь)
        ключ = (строка, столбец, код)
        if ключ in виденные:
            continue
        виденные.add(ключ)
        записи = [f"{строка}:{столбец} ошибка {код} «{текст}»: {сообщение}"]
        for примечание in примечания:
            узел_примечания, пояснение = примечание[0], примечание[1]
            модуль_примечания = примечание[2] if len(примечание) > 2 else модуль
            if модуль_примечания is not модуль or узел_примечания is None:
                continue
            с, ст, т = место_узла(узел_примечания, модуль.исходник)
            записи.append(f"  {с}:{ст} примечание «{т}»: {пояснение}")
        итог.append(((строка, столбец), записи))
    итог.sort(key=lambda запись: запись[0])
    return [строка for _, записи in итог for строка in записи]


def собрать_программу(корень, пути):
    программа = Программа(корень)
    модули = []
    for путь in пути:
        имя = путь.relative_to(корень).with_suffix("").as_posix().replace("/", ".")
        модули.append(программа.загрузить(имя, путь))
    программа.подготовить()
    return программа, модули


def анализировать(программа, раундов=8):
    функции = [
        функция
        for модуль in программа.модули.values()
        for функция in модуль.функции_список
        if функция.тело is not None
    ]
    отчёт = None
    неподдержано = []
    for _ in range(раундов):
        отчёт = Отчёт()
        for запись in программа.ошибки_объявлений:
            отчёт.добавить(*запись)
        неподдержано = []
        изменилось = False
        for функция in функции:
            программа.заголовок(функция)
            функция.замыкание = False
            анализ = Анализ(программа, функция, отчёт)
            анализ.запустить()
            контракт = Решатель(анализ, отчёт).запустить()
            for вложенный in отчёт.анализы:
                Решатель(вложенный, отчёт).запустить()
                неподдержано += [(вложенный.модуль, строка, что) for строка, что in вложенный.неподдержано]
            отчёт.анализы = []
            неподдержано += [(анализ.модуль, строка, что) for строка, что in анализ.неподдержано]
            ключ = {(id(б), id(м)) for б, м, _ in контракт}
            старый = {(id(б), id(м)) for б, м, _ in функция.контракт}
            if ключ != старый:
                функция.контракт = контракт
                изменилось = True
        if not изменилось:
            break
    return отчёт, неподдержано


def проверить_файл(путь):
    путь = pathlib.Path(путь).resolve()
    программа, модули = собрать_программу(путь.parent, [путь])
    отчёт, неподдержано = анализировать(программа)
    return строки_отчёта(отчёт, модули[0]), неподдержано


def проверить_пакет(корень):
    корень = pathlib.Path(корень).resolve()
    пути = sorted(п for п in корень.rglob("*.спл") if п.name not in СЛУЖЕБНЫЕ)
    программа, модули = собрать_программу(корень, пути)
    отчёт, неподдержано = анализировать(программа)
    итог = {модуль.путь.name: строки_отчёта(отчёт, модуль) for модуль in модули}
    библиотека = [
        строка
        for модуль in программа.модули.values()
        if модуль not in модули
        for строка in строки_отчёта(отчёт, модуль)
    ]
    return итог, библиотека, неподдержано


def главная():
    подробно = "--подробно" in sys.argv
    цели = [аргумент for аргумент in sys.argv[1:] if not аргумент.startswith("--")]
    ошибок = 0
    for цель in цели:
        путь = pathlib.Path(цель)
        if путь.is_dir():
            итог, библиотека, неподдержано = проверить_пакет(путь)
            for имя, строки in итог.items():
                print(f"=== {путь}/{имя}: {sum(1 for с in строки if ' ошибка ' in с)} ошибок")
                for строка in строки:
                    print(строка)
                ошибок += sum(1 for с in строки if " ошибка " in с)
            for строка in библиотека:
                print("библиотека:", строка)
        else:
            строки, неподдержано = проверить_файл(путь)
            print(f"=== {путь}")
            for строка in строки:
                print(строка)
            ошибок += sum(1 for с in строки if " ошибка " in с)
        if подробно:
            for модуль, строка, что in неподдержано:
                print(f"  неподдержано {модуль.имя}:{строка}: {что}")
    return ошибок


if __name__ == "__main__":
    sys.exit(1 if главная() else 0)
