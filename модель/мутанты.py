def главная():
    итог = 0
    всего = 0
    for пакет, файл, название, было, стало, код in МУТАНТЫ:
        if код is None:
            continue
        всего += 1
        with tempfile.TemporaryDirectory() as каталог:
            копия = pathlib.Path(каталог) / пакет
            shutil.copytree(КОРПУС / пакет, копия)
            путь = копия / файл
            текст = путь.read_text(encoding="utf-8")
            if было not in текст:
                print(f"✗ {название}: образец не найден")
                continue
            текст = текст.replace(было, стало, 1)
            if "обслужитьПоСсылке" in стало:
                текст += "\nфунк обслужитьПоСсылке(соединение: &tcp.Соединение, простой: время.Длительность)\n{\n    _ = эхо(соединение, простой)\n}\n"
            if "последний = документ" in стало:
                текст = текст.replace("    возврат Успех()\n}\n\nфунк количествоЗначений", "    попытка консоль.печать(последний)\n    возврат Успех()\n}\n\nфунк количествоЗначений", 1)
            путь.write_text(текст, encoding="utf-8")
            результаты, библиотека, неподдержано = проверить_пакет(копия)
            for модуль, строка, что in неподдержано:
                print(f"   неподдержано {модуль.имя}:{строка}: {что}")
            строки = [строка for строки in результаты.values() for строка in строки]
            коды = {строка.split()[2] for строка in строки if " ошибка " in строка}
            if код in коды:
                итог += 1
                print(f"✓ {название}: {код}")
            else:
                print(f"✗ {название}: ждали {код}, получили {sorted(коды) or 'ничего'}")
                for строка in строки:
                    print("   ", строка)
    print(f"итого: {итог} из {всего}")
    return итог == всего


if __name__ == "__main__":
    sys.exit(0 if главная() else 1)
