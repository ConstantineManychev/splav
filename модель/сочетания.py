КОНТЕКСТЫ = ["прямо", "ветвь"]


class Вставка:
    def __init__(self, атом, злой, контекст, суффикс):
        self.атом = атом
        self.злой = злой
        self.контекст = контекст
        self.суффикс = суффикс

    def строки(self):
        исходные = self.атом.злое if self.злой else self.атом.верное
        готовые = [строка.replace("{п}", self.суффикс) for строка in исходные]
        if self.контекст == "ветвь":
            return [f"условие{self.суффикс} = да", f"если условие{self.суффикс}", "{"] + ["    " + с if с else с for с in готовые] + ["}"]
        return готовые

    def якорь(self):
        сдвиг = 3 if self.контекст == "ветвь" else 0
        отступ = 4 if self.контекст == "ветвь" else 0
        строка = self.атом.злое[self.атом.строка].replace("{п}", self.суффикс)
        якорь = self.атом.якорь.replace("{п}", self.суффикс)
        позиция = -1
        for _ in range(self.атом.вхождение):
            позиция = строка.index(якорь, позиция + 1)
        return self.атом.строка + сдвиг, позиция + отступ, якорь

    def ключ(self):
        return (self.атом.имя, self.злой, self.контекст)


def собрать(вставки, отдельно):
    строки = [f"подключить {имя}" for имя in ИМПОРТЫ] + [""] + ОБЩЕЕ.split("\n")
    места = []
    for вставка in вставки:
        if вставка.атом.модульный:
            строки.append("")
            места.append((вставка, len(строки) + 1, 0))
            строки += вставка.строки()
    локальные = [вставка for вставка in вставки if not вставка.атом.модульный]
    if локальные and not отдельно:
        строки += ["", "функ проверка()", "{"]
        for номер, вставка in enumerate(локальные):
            if номер > 0:
                строки.append("")
            места.append((вставка, len(строки) + 1, 4))
            строки += ["    " + с if с else с for с in вставка.строки()]
        строки.append("}")
    for вставка in локальные if отдельно else []:
        строки += ["", f"функ проверка{вставка.суффикс}()", "{"]
        места.append((вставка, len(строки) + 1, 4))
        строки += ["    " + с if с else с for с in вставка.строки()]
        строки.append("}")
    return "\n".join(строки) + "\n", места


ДИАГНОСТИКА = re.compile(r"^( {2})?(\d+):(\d+) (.*)$")


def проверить_текст(текст, имя):
    ЧЕРНОВИК.mkdir(exist_ok=True)
    путь = ЧЕРНОВИК / f"{имя}.спл"
    путь.write_text(текст, encoding="utf-8")
    строки, неподдержано = проверить_файл(путь)
    путь.unlink()
    return строки, неподдержано


def группы(строки):
    итог = []
    for строка in строки:
        if строка.startswith("  ") and итог:
            итог[-1].append(строка)
        else:
            итог.append([строка])
    return итог


def сдвинуть(строка, начало, сдвиг):
    совпадение = ДИАГНОСТИКА.match(строка)
    отступ, номер, столбец, остаток = совпадение.groups()
    номер = int(номер)
    if номер >= начало:
        номер += сдвиг
    return f"{отступ or ''}{номер}:{столбец} {остаток}"


def позиция(группа):
    совпадение = ДИАГНОСТИКА.match(группа[0])
    return int(совпадение.group(2)), int(совпадение.group(3))


class Эталон:
    def __init__(self):
        self.одиночные = {}
        self.замечания = []

    def одиночный(self, вставка, отдельно):
        ключ = вставка.ключ() + (вставка.суффикс, отдельно)
        if ключ not in self.одиночные:
            текст, места = собрать([вставка], отдельно)
            строки, неподдержано = проверить_текст(текст, "одиночный")
            начало = места[0][1]
            self.одиночные[ключ] = (строки, начало, неподдержано, текст, места)
        return self.одиночные[ключ]

    def проверить_одиночный(self, вставка, отдельно):
        строки, начало, неподдержано, текст, места = self.одиночный(вставка, отдельно)
        ошибки = [с for с in строки if " ошибка " in с]
        замечания = [f"неподдержано {модуль.имя}:{строка}: {что}" for модуль, строка, что in неподдержано]
        if not вставка.злой:
            if строки:
                замечания.append("верный вариант отвергнут: " + "; ".join(ошибки or строки))
            return замечания
        строка_якоря, столбец, якорь = вставка.якорь()
        _, начало_атома, отступ = места[0]
        ждём = f"{начало_атома + строка_якоря}:{отступ + столбец + 1} ошибка {вставка.атом.код} «{якорь}»:"
        if len(ошибки) != 1 or not ошибки[0].startswith(ждём):
            замечания.append(f"ждали одну ошибку «{ждём} …», получено: " + ("; ".join(ошибки) if ошибки else "ничего"))
        return замечания

    def ожидаемое(self, вставки, отдельно):
        текст, места = собрать(вставки, отдельно)
        итог = []
        for вставка, начало, _ in места:
            строки, начало_одиночного, _, _, _ = self.одиночный(вставка, отдельно)
            сдвиг = начало - начало_одиночного
            for группа in группы(строки):
                итог.append([сдвинуть(с, начало_одиночного, сдвиг) for с in группа])
        итог.sort(key=позиция)
        return текст, [с for группа in итог for с in группа]


def имя_теста(номер, вставки, отдельно):
    части = []
    for вставка in вставки:
        метка = вставка.атом.имя + ("" if вставка.злой else "Верно") + ("ВВетви" if вставка.контекст == "ветвь" else "")
        части.append(метка)
    вид = "функции" if отдельно or any(в.атом.модульный for в in вставки) else "одна"
    злые = [в for в in вставки if в.злой]
    if len(части) <= 3:
        описание = "+".join(части)
    elif len(злые) == 1:
        описание = f"{len(части)}-атомов-злой-{злые[0].атом.имя}"
    elif not злые:
        описание = f"{len(части)}-атомов-все-верные"
    else:
        описание = f"{len(части)}-атомов-все-злые" + ("-в-ветвях" if all(в.контекст == "ветвь" for в in вставки) else "")
    return f"{номер:03d}-{вид}-{описание}"


def наборы(эталон):
    годные_локальные = []
    годные_модульные = []
    отчёт = []
    for атом in ЛОКАЛЬНЫЕ:
        for контекст in КОНТЕКСТЫ:
            for злой in (True, False):
                вставка = Вставка(атом, злой, контекст, str(ЛОКАЛЬНЫЕ.index(атом) + 1))
                замечания = эталон.проверить_одиночный(вставка, False)
                отчёт.append((вставка, замечания))
            if not any(з for в, з in отчёт[-2:]):
                годные_локальные.append((атом, контекст))
    for атом in МОДУЛЬНЫЕ:
        for злой in (True, False):
            вставка = Вставка(атом, злой, "прямо", str(len(ЛОКАЛЬНЫЕ) + МОДУЛЬНЫЕ.index(атом) + 1))
            отчёт.append((вставка, эталон.проверить_одиночный(вставка, False)))
        if not any(з for в, з in отчёт[-2:]):
            годные_модульные.append(атом)
    return годные_локальные, годные_модульные, отчёт


def вставка(атом, злой, контекст="прямо"):
    if атом.модульный:
        return Вставка(атом, злой, "прямо", str(len(ЛОКАЛЬНЫЕ) + МОДУЛЬНЫЕ.index(атом) + 1))
    return Вставка(атом, злой, контекст, str(ЛОКАЛЬНЫЕ.index(атом) + 1))


def тесты(годные_локальные, годные_модульные):
    случай = random.Random(20261104)
    прямые = [атом for атом, контекст in годные_локальные if контекст == "прямо"]
    контексты = {}
    for атом, контекст in годные_локальные:
        контексты.setdefault(атом.имя, []).append(контекст)
    список = []
    for атом, контекст in годные_локальные:
        список.append(([вставка(атом, True, контекст)], False))
        список.append(([вставка(атом, False, контекст)], False))
    for атом in годные_модульные:
        список.append(([вставка(атом, True)], False))
        список.append(([вставка(атом, False)], False))
    for первый, второй in itertools.permutations(прямые, 2):
        список.append(([вставка(первый, True), вставка(второй, True)], False))
    тройки = list(itertools.combinations(прямые, 3))
    случай.shuffle(тройки)
    for тройка in тройки[:60]:
        порядок = list(тройка)
        случай.shuffle(порядок)
        список.append(([вставка(атом, True, случай.choice(контексты[атом.имя])) for атом in порядок], False))
    for злой in прямые:
        список.append(([вставка(атом, атом is злой) for атом in прямые], False))
    список.append(([вставка(атом, True) for атом in прямые], False))
    список.append(([вставка(атом, False) for атом in прямые], False))
    список.append(([вставка(атом, True, "ветвь") for атом in прямые if "ветвь" in контексты[атом.имя]], False))
    for первый, второй in itertools.combinations(годные_модульные, 2):
        список.append(([вставка(первый, True), вставка(второй, True)], False))
    for атом in годные_модульные:
        соседи = случай.sample(прямые, 3)
        список.append(([вставка(атом, True)] + [вставка(сосед, True) for сосед in соседи], True))
    список.append(([вставка(атом, True) for атом in годные_модульные] + [вставка(атом, True) for атом in прямые], True))
    список.append(([вставка(атом, True) for атом in годные_модульные] + [вставка(атом, True) for атом in прямые], False))
    список.append(([вставка(атом, False) for атом in годные_модульные] + [вставка(атом, False) for атом in прямые], False))
    return список


